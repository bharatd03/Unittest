# ============================================================================ diagnostics
DIAG = re.compile(r"^(?P<file>[^\s:][^:]*?|[A-Za-z]:[^:]*?):(?P<line>\d+):(?:(?P<col>\d+):)?\s*"
                  r"(?P<sev>fatal error|error|warning|note):\s*(?P<msg>.*)$")
UNDEF = [re.compile(r"undefined reference to [`'\"]?([^'`\"\s]+)[`'\"]?"),
         re.compile(r"undefined symbol:\s*(\S+)"),
         re.compile(r"unresolved external symbol\s+\"?([^\s\"]+)")]
DUPDEF = [re.compile(r"multiple definition of [`'\"]?([^'`\"\s]+)[`'\"]?"),
          re.compile(r"duplicate symbol:?\s*'?([^'\s]+)'?")]


def categorize(message: str) -> str:
    m = message.lower()
    rules = [("file not found", "missing_header"), ("no such file", "missing_header"),
             ("undeclared", "undeclared_symbol"), ("was not declared", "undeclared_symbol"),
             ("implicit declaration", "undeclared_symbol"), ("unknown type name", "undeclared_symbol"),
             ("too few arguments", "incorrect_arguments"), ("too many arguments", "incorrect_arguments"),
             ("no matching function", "incorrect_arguments"), ("incompatible", "incorrect_arguments"),
             ("redefinition", "duplicate_definition"), ("conflicting types", "incorrect_signature"),
             ("expected", "syntax")]
    for needle, category in rules:
        if needle in m:
            return category
    return "other"


def parse_compiler_output(text: str, default_role: str = "") -> list[uc.Diagnostic]:
    diags: list[uc.Diagnostic] = []
    for line in text.splitlines():
        m = DIAG.match(line.strip())
        if m and m.group("sev") in ("error", "fatal error"):
            path = m.group("file").replace("\\", "/")
            role = default_role
            sym = re.search(r"'([A-Za-z_][\w:]*)'", m.group("msg"))
            diags.append(uc.Diagnostic(file=path, line=int(m.group("line")), column=int(m.group("col") or 0),
                                       severity="error", message=m.group("msg")[:400],
                                       category=categorize(m.group("msg")), symbol=sym.group(1) if sym else "",
                                       role=role))
            continue
        for pattern in UNDEF:
            u = pattern.search(line)
            if u:
                diags.append(uc.Diagnostic(message=line.strip()[:400], category="undefined_reference",
                                           symbol=u.group(1).strip("`'\"").split("(")[0], role="link"))
                break
        else:
            for pattern in DUPDEF:
                d = pattern.search(line)
                if d:
                    diags.append(uc.Diagnostic(message=line.strip()[:400], category="duplicate_definition",
                                               symbol=d.group(1).strip("`'\""), role="link"))
                    break
    seen, unique = set(), []
    for d in diags:
        key = (d.file, d.line, d.category, d.symbol, d.message if not d.symbol else "")
        if key not in seen:
            seen.add(key)
            unique.append(d)
    return unique


def parse_run_output(text: str) -> tuple[list[uc.TestResult], dict[str, str], tuple[int, int, int] | None]:
    results: dict[str, uc.TestResult] = {}
    started: list[str] = []
    observed: dict[str, str] = {}
    summary = None
    for line in text.splitlines():
        parts = line.rstrip("\r").split("|")
        if parts[0] == "UT_START" and len(parts) >= 2:
            started.append(parts[1])
        elif parts[0] == "UT_RESULT" and len(parts) >= 3:
            if parts[2] == "PASS":
                results[parts[1]] = uc.TestResult(name=parts[1], status="passed")
            elif parts[2] == "TIMEOUT":                              # call budget, time limit [A3-45b, A3-45d]
                results[parts[1]] = uc.TestResult(name=parts[1], status="timeout",
                                                  message=parts[3] if len(parts) > 3 else "timeout")
            elif parts[2] == "CRASH":                                         # a child process [A3-45c]
                sig = re.search(r"signal (\d+)", parts[3] if len(parts) > 3 else "")
                results[parts[1]] = uc.TestResult(name=parts[1], status="crashed", message="crashed: " + (
                    _exit_text(-int(sig.group(1))) if sig else (parts[3] if len(parts) > 3 else "")))
            elif len(parts) >= 8:
                results[parts[1]] = uc.TestResult(name=parts[1], status="failed", file=parts[3],
                                                  line=int(parts[4]) if parts[4].isdigit() else 0,
                                                  message=parts[5], expected=parts[6], actual=parts[7])
        elif parts[0] == "UT_OBSERVE" and len(parts) >= 4:
            observed[parts[2]] = parts[3]
        elif parts[0] == "UT_SUMMARY" and len(parts) >= 4:
            summary = (int(parts[1]), int(parts[2]), int(parts[3]))
    for name in started:
        if name not in results:
            status = "timeout" if "UT_TIMEOUT" in text else "crashed"
            results[name] = uc.TestResult(name=name, status=status, message="test did not complete")
    return list(results.values()), observed, summary


# ============================================================================ coverage parsing
def _fn_for_line(functions: list[uc.FunctionInfo], line: int) -> str:
    for f in functions:
        if f.line_start <= line <= f.line_end:
            return f.name
    return "<file>"


def parse_lcov(text: str, sut_suffix: str) -> dict[int, int]:
    """Line -> execution count for the SUT file (LCOV 'DA' records)."""
    lines, active = {}, False
    for raw in text.splitlines():
        if raw.startswith("SF:"):
            active = raw[3:].replace("\\", "/").endswith(sut_suffix)
        elif active and raw.startswith("DA:"):
            line, count = raw[3:].split(",")[:2]
            lines[int(line)] = lines.get(int(line), 0) + int(count)
        elif raw.startswith("end_of_record"):
            active = False
    return lines


MCDC_DECISION = re.compile(r"MC/DC Decision Region \((\d+):(\d+)\) to \((\d+):(\d+)\)")
MCDC_CONDITION = re.compile(r"Condition C(\d+) --> \((\d+):(\d+)\)")
MCDC_VECTOR = re.compile(r"^\s*\|?\s*\d+\s*\{\s*([TF\-,\s]+?)\s*=\s*([TF])\s*\}")
MCDC_PAIR = re.compile(r"C(\d+)-Pair:\s*(not covered|covered.*)")


def parse_mcdc_show(text: str) -> list[dict[str, Any]]:
    """Decisions from `llvm-cov show --show-mcdc`: conditions, executed vectors, pairs."""
    decisions, current = [], None
    for raw in text.splitlines():
        line = raw.strip().lstrip("|").strip()
        m = MCDC_DECISION.search(line)
        if m:
            current = {"line": int(m.group(1)), "column": int(m.group(2)), "end_line": int(m.group(3)),
                       "conditions": {}, "vectors": [], "pairs": {}}
            decisions.append(current)
            continue
        if current is None:
            continue
        c = MCDC_CONDITION.search(line)
        if c:
            current["conditions"][int(c.group(1))] = (int(c.group(2)), int(c.group(3)))
            continue
        v = MCDC_VECTOR.match(raw.strip().lstrip("|"))
        if v:
            values = [x.strip() for x in v.group(1).split(",")]
            current["vectors"].append(("".join(values), v.group(2)))
            continue
        p = MCDC_PAIR.search(line)
        if p:
            current["pairs"][int(p.group(1))] = p.group(2).startswith("covered")
    return decisions


def llvm_coverage(cov: dict[str, Any], lcov_text: str, show_text: str, sut_rel: str,
                  functions: list[uc.FunctionInfo], mcdc_enabled: bool,
                  unreachable: set[int] | frozenset[int] = frozenset()) -> uc.CoverageReport:
    """unreachable: lines after an endless loop, never counted as executed [A3-HW5]."""
    sut_suffix = sut_rel.replace("\\", "/")
    dead = " - after an endless loop: no test can reach it [A3-HW5]"
    data = (cov.get("data") or [{}])[0]
    line_counts = parse_lcov(lcov_text, sut_suffix)
    per_fn: dict[str, dict[str, Any]] = {f.name: {"info": f, "lc": [0, 0], "sc": [0, 0], "bc": [0, 0], "dc": [0, 0],
                                                    "mc": [0, 0], "gaps": [], "executed": False} for f in functions}
    covered_items: list[str] = []
    other = {"info": None, "lc": [0, 0], "sc": [0, 0], "bc": [0, 0], "dc": [0, 0], "mc": [0, 0], "gaps": [],
             "executed": False}

    def bucket(line: int) -> dict[str, Any]:
        return per_fn.get(_fn_for_line(functions, line), other)

    # LC
    for line, count in sorted(line_counts.items()):
        count = 0 if line in unreachable else count
        b = bucket(line)
        b["lc"][1] += 1
        if count > 0:
            b["lc"][0] += 1
            b["executed"] = True
            covered_items.append(f"LC:{line}")
        else:
            b["gaps"].append(uc.GapItem(gap_id=f"LC:{_fn_for_line(functions, line)}:{line}",
                                        function=_fn_for_line(functions, line), metric="LC", line=line,
                                        detail="line never executed" + (dead if line in unreachable else "")))
    # SC (code regions) and BC, from the functions' region/branch records in the SUT file
    seen_regions, seen_branches = set(), set()
    branch_records = []
    for fn in data.get("functions", []):
        names = [n.replace("\\", "/") for n in fn.get("filenames", [])]
        for region in fn.get("regions", []):
            if len(region) < 8:
                continue
            ls, cs, le, ce, count, file_id, _exp, kind = region[:8]
            if kind != 0 or file_id >= len(names) or not names[file_id].endswith(sut_suffix):
                continue
            key = (ls, cs, le, ce)
            if key in seen_regions:
                continue
            seen_regions.add(key)
            count = 0 if ls in unreachable else count
            b = bucket(ls)
            b["sc"][1] += 1
            if count > 0:
                b["sc"][0] += 1
                covered_items.append(f"SC:{ls}:{cs}")
            else:
                b["gaps"].append(uc.GapItem(gap_id=f"SC:{_fn_for_line(functions, ls)}:{ls}:{cs}",
                                            function=_fn_for_line(functions, ls), metric="SC", line=ls, column=cs,
                                            detail=f"code region {ls}:{cs}-{le}:{ce} never executed"))
        for br in fn.get("branches", []):
            if len(br) < 8:
                continue
            ls, cs, le, ce, t_count, f_count, file_id = br[:7]
            if file_id >= len(names) or not names[file_id].endswith(sut_suffix):
                continue
            key = (ls, cs, le, ce)
            if key in seen_branches:
                continue
            seen_branches.add(key)
            if ls in unreachable:
                t_count = f_count = 0
            branch_records.append((ls, cs, t_count, f_count))
    # MC/DC decisions with executed vectors
    decisions = parse_mcdc_show(show_text) if mcdc_enabled else []
    for d in decisions:
        if d["line"] in unreachable:
            d["vectors"], d["pairs"] = [], {}
    in_decision = set()
    for d in decisions:
        for (cl, cc) in d["conditions"].values():
            in_decision.add((cl, cc))
    # Several condition records on one line outside any measured decision: a multi-condition
    # decision that MC/DC did not instrument (or MC/DC is off). Its decision outcome is unknown, so
    # DC and MC/DC are reported as not measured instead of being counted per condition [A3-33a].
    per_line: dict[int, list[int]] = {}
    for ls, cs, _t, _f in branch_records:
        if (ls, cs) not in in_decision:
            per_line.setdefault(ls, []).append(cs)
    source = {int(m.group(1)): m.group(2) for m in re.finditer(r"^\s*(\d+)\|[^|\n]*\|(.*)$", show_text, re.M)}

    def joined(line: int, columns: list[int]) -> bool:
        """Two conditions on one line belong to one decision when && or || joins them; two separate
        one-condition decisions (two ?: in a constructor's initializer list) do not [A3-33a]."""
        text = source.get(line)
        if text is None:
            return True                                   # no source text: assume one decision (not measured)
        cols = sorted(columns)
        return any(re.search(r"&&|\|\||\band\b|\bor\b", text[a - 1: b - 1]) for a, b in zip(cols, cols[1:]))
    unmeasured = {line for line, cols in per_line.items() if len(cols) > 1 and joined(line, cols)}
    for ls, cs, t_count, f_count in branch_records:
        b = bucket(ls)
        fn_name = _fn_for_line(functions, ls)
        for outcome, count in (("T", t_count), ("F", f_count)):
            b["bc"][1] += 1
            if count > 0:
                b["bc"][0] += 1
                covered_items.append(f"BC:{ls}:{cs}:{outcome}")
            else:
                b["gaps"].append(uc.GapItem(gap_id=f"BC:{fn_name}:{ls}:{cs}:{outcome}", function=fn_name,
                                            metric="BC", line=ls, column=cs,
                                            detail=f"condition at {ls}:{cs} never {'true' if outcome == 'T' else 'false'}"))
        if (ls, cs) not in in_decision and ls not in unmeasured:   # one-condition decision: DC = both outcomes
            b["dc"][1] += 1
            if t_count > 0 and f_count > 0:
                b["dc"][0] += 1
                covered_items.append(f"DC:{ls}:{cs}")
            else:
                b["gaps"].append(uc.GapItem(gap_id=f"DC:{fn_name}:{ls}:{cs}", function=fn_name, metric="DC",
                                            line=ls, column=cs, detail="decision not evaluated both ways",
                                            observed=[o for o, c in (("T", t_count), ("F", f_count)) if c > 0]))
    for d in decisions:
        b = bucket(d["line"])
        fn_name = _fn_for_line(functions, d["line"])
        results = {r for _, r in d["vectors"]}
        observed = [f"{vec}={res}" for vec, res in d["vectors"]]
        b["dc"][1] += 1
        if {"T", "F"} <= results:
            b["dc"][0] += 1
            covered_items.append(f"DC:{d['line']}:{d['column']}")
        else:
            b["gaps"].append(uc.GapItem(gap_id=f"DC:{fn_name}:{d['line']}:{d['column']}", function=fn_name,
                                        metric="DC", line=d["line"], column=d["column"],
                                        detail="decision not evaluated both ways", observed=observed))
        for index in sorted(d["conditions"]):
            b["mc"][1] += 1
            if d["pairs"].get(index):
                b["mc"][0] += 1
                covered_items.append(f"MCDC:{d['line']}:{d['column']}:{index}")
            else:
                b["gaps"].append(uc.GapItem(gap_id=f"MCDC:{fn_name}:{d['line']}:{d['column']}:C{index}",
                                            function=fn_name, metric="MCDC", line=d["line"], column=d["column"],
                                            condition_index=index - 1, observed=observed,
                                            detail=f"condition C{index} not shown to independently affect the decision"))
    return _assemble("llvm", per_fn, other, covered_items, mcdc_measured=mcdc_enabled and not unmeasured,
                     sc_measured=True, dc_measured=not unmeasured)



def mcdc_pair_found(vectors: set[str], index: int) -> bool:
    """LLVM's independence pair for condition ``index``: two executed vectors ("TF-=T") that
    differ in that condition and in the outcome; other conditions are equal or not evaluated."""
    parsed = [(v.partition("=")[0], v.partition("=")[2]) for v in vectors]
    for (a, ra), (b, rb) in itertools.combinations(parsed, 2):
        if ra == rb or len(a) != len(b) or index >= len(a) or "-" in (a[index], b[index]) or a[index] == b[index]:
            continue
        if all(x == y or "-" in (x, y) for k, (x, y) in enumerate(zip(a, b)) if k != index):
            return True
    return False


def _assemble(kind: str, per_fn: dict[str, dict[str, Any]], other: dict[str, Any], covered_items: list[str], *,
              mcdc_measured: bool, sc_measured: bool, dc_measured: bool) -> uc.CoverageReport:
    totals = {k: [0, 0] for k in ("lc", "sc", "bc", "dc", "mc")}
    functions = []
    for name, b in list(per_fn.items()) + ([("<file>", other)] if other["lc"][1] or other["gaps"] else []):
        for k in totals:
            totals[k][0] += b[k][0]
            totals[k][1] += b[k][1]
        info = b["info"]
        functions.append(uc.FunctionCoverage(
            name=name, line_start=info.line_start if info else 0, line_end=info.line_end if info else 0,
            executed=b["executed"],
            metrics=uc.Metrics(LC=uc.metric(*b["lc"]), SC=uc.metric(*b["sc"], measured=sc_measured),
                               BC=uc.metric(*b["bc"]), DC=uc.metric(*b["dc"], measured=dc_measured),
                               MCDC=uc.metric(*b["mc"], measured=mcdc_measured)),
            gaps=b["gaps"]))
    file_metrics = uc.Metrics(LC=uc.metric(*totals["lc"]), SC=uc.metric(*totals["sc"], measured=sc_measured),
                              BC=uc.metric(*totals["bc"]), DC=uc.metric(*totals["dc"], measured=dc_measured),
                              MCDC=uc.metric(*totals["mc"], measured=mcdc_measured))
    return uc.CoverageReport(toolchain=kind, definitions=DEFINITIONS[kind], measured=True,
                             file_metrics=file_metrics, functions=functions, covered_items=sorted(set(covered_items)))


def required_complete(cov: uc.CoverageReport, required: list[str],
                      targets: dict[str, str] | None = None) -> tuple[bool, list[str]]:
    """A3-65..67, COV-1: complete only when every required, applicable metric has reached its target by
    measurement (100 % unless the SUT file's ASIL level sets another). Nothing else counts (COV-3)."""
    missing = []
    for name in required:
        value: uc.MetricValue = getattr(cov.file_metrics, name)
        target = (targets or {}).get(name, "100")
        if value.status == "not_applicable":
            continue
        if value.status in ("complete", "incomplete") and uc.target_met(value.percent, target):
            continue
        missing.append(f"{name} {value.status}" + (f" {value.percent}% (target {uc.target_text(target)})"
                                                    if value.status == "incomplete" else ""))
    return not missing, missing


