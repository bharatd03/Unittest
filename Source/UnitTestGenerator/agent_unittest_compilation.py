def load_section(config_path: str | None, section: str) -> dict[str, Any]:
    if not config_path:
        return {}
    path = Path(config_path)
    raw = json.loads(path.read_text(encoding="utf-8"))
    data = dict(raw.get(section, {}))
    for key in ("work_dir", "tools_manifest"):
        if data.get(key) and not Path(data[key]).is_absolute():
            data[key] = str((path.resolve().parent / data[key]).resolve())
    return data


