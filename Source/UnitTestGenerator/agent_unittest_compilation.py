    def _target_keywords(self, layout: uc.LayoutProfile, desc: uc.BuildDescription, chain: Toolchain) -> uc.BuildDescription:
        """A3-HW2: host definitions for the target compiler keywords the SUT's errors name, recorded in the
        build description, so the front end (Agent1) and every build use them."""
        repo = Path(layout.repo_root)
        cpp = layout.language == "cpp"
        sut = repo / layout.sut_file
        if not sut.is_file():
            return desc
        flags = list(desc.sut_flags)
        for _ in range(4):
            probe = layout.model_copy(update={"compile_flags": flags, "build": desc})
            full = self.sut_flags(probe, repo)
            std = [] if any(f.startswith("-std=") for f in full) else [f"-std={self.cfg.cxx_std if cpp else self.cfg.c_std}"]
            header = ["-x", "c++" if cpp else "c"] if sut.suffix.lower() in (".h", ".hpp", ".hh", ".hxx") else []
            code, text = _run([chain.cxx if cpp else chain.cc, *header, "-fsyntax-only", "-w", *std, *full,
                               *chain.compile_flags(cpp), str(sut)], repo, self.cfg.compile_timeout, chain.env())
            if code == 0 or code in (-126, -127):
                break
            added = []
            for raw in text.splitlines():
                m = DIAG.match(raw.strip())
                if not m or m.group("sev") not in ("error", "fatal error"):
                    continue
                where = Path(m.group("file")) if Path(m.group("file")).is_absolute() else repo / m.group("file")
                source = ""
                if where.is_file():
                    lines = where.read_text(encoding="utf-8", errors="replace").splitlines()
                    n = int(m.group("line"))
                    source = lines[n - 1] if 0 < n <= len(lines) else ""
                for kw, value in TARGET_KEYWORDS.items():
                    name = kw.split("(")[0]
                    if any(f == f"-D{name}" or f.startswith((f"-D{name}=", f"-D{name}(")) for f in flags + full):
                        continue
                    if re.search(r"(?<!\w)" + re.escape(name) + r"(?!\w)", source + " " + m.group("msg")):
                        flags.append(f"-D{kw}={value}")
                        try:
                            rel = str(where.resolve().relative_to(repo.resolve())).replace("\\", "/")
                        except (ValueError, OSError):
                            rel = m.group("file")
                        added.append(f"target keyword {name} defined for the host as '{value or '(nothing)'}' "
                                     f"({rel}:{m.group('line')}) [A3-HW2]")
            if not added:
                break
            desc = desc.model_copy(update={"sut_flags": flags, "notes": list(desc.notes) + added})
        return desc

