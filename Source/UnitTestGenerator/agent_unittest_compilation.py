def _balanced(text: str, open_at: int) -> int:
    """Index after the parenthesis that closes the one at open_at (strings and characters skipped)."""
    depth, k, quote = 0, open_at, ""
    while k < len(text):
        c = text[k]
        if quote:
            if c == "\\":
                k += 2
                continue
            if c == quote:
                quote = ""
        elif c in "\"'":
            quote = c
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return k + 1
        k += 1
    return -1


def _top_split(text: str, sep: str) -> list[str]:
    parts, depth, quote, cur = [], 0, "", []
    k = 0
    while k < len(text):
        c = text[k]
        if quote:
            cur.append(c)
            if c == "\\" and k + 1 < len(text):
                cur.append(text[k + 1])
                k += 2
                continue
            if c == quote:
                quote = ""
        elif c in "\"'":
            quote = c
            cur.append(c)
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            depth -= 1
            cur.append(c)
        elif c == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        k += 1
    parts.append("".join(cur))
    return parts


def neutralize_asm(text: str, line: int | None = None, mnemonics: set[str] | None = None) -> tuple[str, list[tuple[int, str]]]:
    """A3-HW3: asm statements replaced by an empty statement whose output operands are set to 0: the one
    on ``line`` (1-based), or every one whose instruction starts with one of ``mnemonics``. The line
    count stays the same. Returns the new text and (line, instruction) of every replaced statement."""
    out, replaced, pos = [], [], 0
    for m in ASM_START.finditer(text):
        if m.start() < pos:
            continue
        end = _balanced(text, m.end() - 1)
        if end < 0:
            continue
        first = text.count("\n", 0, m.start()) + 1
        last = text.count("\n", 0, end) + 1
        inner = text[m.end(): end - 1]
        parts = _top_split(inner, ":")
        template = " ".join(re.findall(r'"((?:[^"\\]|\\.)*)"', parts[0])).replace("\\n", "; ").replace("\\t", " ").strip()
        word = (re.match(r"\s*([A-Za-z_.][\w.]*)", template) or re.match(r"()", "")).group(1).lower()
        hit = (line is not None and first <= line <= last) or (mnemonics and word in {x.lower() for x in mnemonics})
        if not hit:
            continue
        outputs = []
        if len(parts) > 1:
            for operand in _top_split(parts[1], ","):
                o = re.search(r'"[^"]*"\s*(\(.*\))\s*$', operand.strip(), re.S)
                if o:
                    outputs.append(f"{o.group(1)} = (__typeof__({o.group(1)}))ut_asm_result()")
        segment = text[m.start(): end]
        keep = "".join(re.findall(r"\\?\r?\n", segment))         # same lines; macro continuations kept
        replacement = (", ".join(outputs) if outputs else "((void)0)") + " /* target asm [A3-HW3] */" + keep
        out.append(text[pos: m.start()])
        out.append(replacement)
        pos = end
        replaced.append((first, template[:60] or "asm"))
    out.append(text[pos:])
    return "".join(out), replaced


