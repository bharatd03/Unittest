def _plain(t: str) -> str:
    return re.sub(r"\s+", " ", t.replace("const ", "").replace("volatile ", "")).strip()


class FuzzPlan:
    """C/C++ source of a libFuzzer target for one function: the input bytes are decoded into the
    function's parameters and the values of the controlled stubs; with UT_FUZZ_PRINT set, the
    decoded values are printed as C expressions, so an input becomes a readable test [A3-FZ2]."""

    def __init__(self, fn: uc.FunctionInfo, layout: uc.LayoutProfile, controls: list[tuple[str, str]],
                 budget: int = 100_000):
        """controls: (lvalue, type) a test may set before the call - stub return values and
        variables decided stub [A2-21g, A2-21j]. budget: stub calls per input [A3-45b]."""
        self.fn, self.layout, self.cpp = fn, layout, layout.language == "cpp"
        self.budget = budget
        self.lines: list[str] = []
        self.prints: list[str] = []
        self.pointees: dict[str, list[str]] = {}       # struct label -> objects its pointer fields point to
        self.body = ""                                  # the function's source: which fields it checks for NULL
        self.size = 0
        self.problem = ""
        self.controls = [(n, r) for n, t in controls for r in [self._resolve(_plain(t))]
                         if SCALAR.match(r) and r != "void"]

    def _resolve(self, t: str) -> str:
        """A1-DA21: a project typedef resolved to the type it names (kTick_t -> uint32_t)."""
        for _ in range(8):
            nxt = self.layout.typedefs.get(t) or self.layout.typedefs.get(t.split("::")[-1])
            if not nxt or _plain(nxt) == t:
                break
            t = _plain(nxt)
        return t

    def take(self, var: str, ctype: str) -> None:
        self.lines.append(f"    {ctype} {var}; ut_take(&{var}, sizeof {var});")
        self.size += 8

    def print_scalar(self, label: str, expr: str, ctype: str) -> None:
        if FLOAT_T.search(ctype):
            self.prints.append(f'printf("|{label}=%.17g", (double)({expr}));')
        elif "bool" in ctype:
            self.prints.append(f'printf("|{label}=%d", ({expr}) ? 1 : 0);')
        elif "unsigned" in ctype or ctype.startswith("uint") or ctype == "size_t":
            self.prints.append(f'printf("|{label}=%llu", (unsigned long long)({expr}));')
        else:
            self.prints.append(f'printf("|{label}=%lld", (long long)({expr}));')

    def sanitize_float(self, expr: str) -> None:
        self.lines.append(f"    if (!(({expr}) == ({expr})) || ({expr}) > 1e15 || ({expr}) < -1e15) {expr} = 0;")

    def fields(self, base: str, fields: list[uc.FieldInfo], label: str, top: bool = True) -> bool:
        """Prints a struct as an aggregate initializer {a, b, {c, d}}; scalar fields only."""
        self.prints.append('printf("{");')
        for k, f in enumerate(fields):
            if k:
                self.prints.append('printf(", ");')
            expr = f"{base}.{f.name}"
            if f.kind in ("int", "bool", "float", "enum"):
                if f.kind == "float":
                    self.sanitize_float(expr)
                self._print_raw(expr, f.type, f.kind)
            elif f.kind == "array" and f.array_len and SCALAR.match(_plain(re.sub(r"\[.*$", "", f.type))):
                self.prints.append('printf("{");')
                for j in range(min(f.array_len, 64)):
                    if j:
                        self.prints.append('printf(", ");')
                    self._print_raw(f"{expr}[{j}]", re.sub(r"\[.*$", "", f.type), "float" if FLOAT_T.search(f.type) else "int")
                self.prints.append('printf("}");')
            elif f.kind == "struct" and f.fields:
                if not self.fields(expr, f.fields, label, top=False):
                    return False
            elif f.kind == "callback":                         # no function to call: NULL [A1-DA21]
                self.lines.append(f"    {expr} = 0;")
                self.prints.append('printf("0");')
            elif f.kind == "pointer" and top:                   # a zeroed object of its own [A3-FZ2, A2-21ad]
                var = f"ut_p{label[1:]}_{k}"
                definition, address = uc.pointee_object(f.base, var, self.cpp)
                self.pointees.setdefault(label, []).append(definition)
                if uc.null_checked(f.name, self.body):           # NULL too, chosen by an input byte
                    self.take(f"{var}_z", "unsigned char")
                    self.lines.append(f"    {definition} {expr} = ({var}_z % 4u) == 0 ? 0 : {address};")
                    self.prints.append(f'printf("%s", ({var}_z % 4u) == 0 ? "0" : "{address}");')
                else:
                    self.lines.append(f"    {definition} {expr} = {address};")
                    self.prints.append(f'printf("{address}");')
            else:
                self.problem = f"field {f.name} of type {f.type} cannot be generated"
                return False
        self.prints.append('printf("}");')
        return True

    def _print_raw(self, expr: str, ctype: str, kind: str) -> None:
        if kind == "float":
            self.prints.append(f'printf("%.17g", (double)({expr}));')
        elif kind == "bool":
            self.prints.append(f'printf("%d", ({expr}) ? 1 : 0);')
        else:
            self.prints.append(f'printf("%lld", (long long)({expr}));')

    def build(self, sut: Path) -> str | None:
        fn = self.fn
        if "::" in fn.qualified_name and fn.qualified_name.count("::") > 0 and self._is_method():
            self.problem = "a class method needs an object"
            return None
        if not fn.from_frontend:
            self.problem = "no parameter types from the compiler front end"
            return None
        args = []
        for i, (lvalue, ctype) in enumerate(self.controls):
            boolean = "bool" in ctype
            self.take(f"ut_s{i}", "unsigned char" if boolean else ctype)
            if FLOAT_T.search(ctype):
                self.sanitize_float(f"ut_s{i}")
            value = f"(ut_s{i} & 1)" if boolean else f"ut_s{i}"
            self.lines.append(f"    {lvalue} = {value};")
            self.print_scalar(f"S:{lvalue}", value, ctype)
        for i, p in enumerate(fn.params):
            var = f"ut_a{i}"
            t = _plain(p.type)
            if p.kind in ("int", "float", "bool"):
                ctype = "unsigned char" if p.kind == "bool" else t
                self.take(var, ctype)
                if p.kind == "float":
                    self.sanitize_float(var)
                self.print_scalar(f"A{i}", f"({var} & 1)" if p.kind == "bool" else var, "bool" if p.kind == "bool" else ctype)
                args.append(var if p.kind != "bool" else f"({var} & 1)")
            elif p.kind == "enum" and p.enum_values:
                self.take(f"{var}_k", "unsigned char")
                names = p.enum_values
                self.lines.append(f"    unsigned {var}_i = {var}_k % {len(names)}u;")
                self.prints.append(f'printf("|E{i}=%u", {var}_i);')
                table = ", ".join(names)
                self.lines.append(f"    static const {t} {var}_t[] = {{{table}}};")
                args.append(f"{var}_t[{var}_i]")
            elif p.kind == "ptr_scalar" and SCALAR.match(self._resolve(_plain(p.base))):
                base = _plain(p.base)
                self.take(f"{var}_v", "unsigned char" if "bool" in base else base)
                if FLOAT_T.search(base):
                    self.sanitize_float(f"{var}_v")
                self.print_scalar(f"P{i}", f"{var}_v", base)
                if p.nullable:
                    self.take(f"{var}_z", "unsigned char")
                    self.prints.append(f'printf("|N{i}=%d", ({var}_z % 8u) == 0);')
                    args.append(f"(({var}_z % 8u) == 0 ? {'nullptr' if self.cpp else 'NULL'} : "
                                f"({base} *)&{var}_v)" if "bool" not in base else f"(({var}_z % 8u) == 0 ? 0 : &{var}_v)")
                else:
                    args.append(f"({base} *)&{var}_v" if "bool" not in base else f"&{var}_v")
            elif p.kind in ("struct", "ptr_struct") and p.fields:
                base = _plain(p.base or p.type)
                self.lines.append(f"    {base} {var}; ut_take(&{var}, sizeof {var});")
                self.size += 64
                self.prints.append(f'printf("|T{i}=");')
                if not self.fields(var, p.fields, f"T{i}"):
                    return None
                args.append(f"&{var}" if p.kind == "ptr_struct" else var)
            elif p.kind == "cstring":
                self.lines.append(f"    char {var}[33]; ut_take({var}, 32); {var}[32] = 0;")
                self.size += 32
                self.prints.append(f'printf("|C{i}="); ut_print_str({var});')
                args.append(var)
            else:
                self.problem = f"parameter {p.name} ({p.type}) cannot be generated"
                return None
        call = f"{fn.qualified_name}({', '.join(args)})"
        include_stubs = "#include \"ut_stubs.h\"\n" if any(n.startswith("ut_stub_") for n, _ in self.controls) else ""
        return "\n".join([
            "/* libFuzzer target generated by agent_unittest_compilation [A3-FZ2]. */",
            "#if !defined(_WIN32) && !defined(_GNU_SOURCE)\n#define _GNU_SOURCE 1\n#endif",       # sigaction, mmap [A3-FZ12]
            "#if !defined(_WIN32) && !defined(_DARWIN_C_SOURCE)\n#define _DARWIN_C_SOURCE 1\n#endif",
            "#include <stdint.h>", "#include <stddef.h>", "#include <string.h>", "#include <stdio.h>",
            "#include <stdlib.h>", "#include <setjmp.h>", "" if self.cpp else "#include <stdbool.h>",
            FUZZ_REGISTERS,                                                                           # A3-FZ12
            '#include "ut_harness.h"', include_stubs + f'#include "{str(sut).replace(chr(92), "/")}"',
            # an input that keeps calling stubs ends like a test over its call budget [A3-45b]
            "static jmp_buf ut_fz_jump; static unsigned long ut_fz_calls; static volatile int ut_fz_active;",
            ('extern "C" ' if self.cpp else "") + "void ut_stub_call(void) { if (ut_fz_active && ++ut_fz_calls > "
            f"{int(self.budget)}UL) {{ ut_fz_active = 0; longjmp(ut_fz_jump, 1); }} }}",
            "unsigned long long ut_asm_value; unsigned long long ut_asm_result(void) { return ut_asm_value; }",
            uc.sut_reset_source(self.layout.sut_state, self.cpp) if self.layout.sut_state else "",   # A3-FZ8
            "static const uint8_t *ut_p; static size_t ut_left;",
            "static void ut_take(void *out, size_t n) { size_t k = n < ut_left ? n : ut_left; memset(out, 0, n); "
            "memcpy(out, ut_p, k); ut_p += k; ut_left -= k; }",
            "static void ut_print_str(const char *s) { printf(\"\\\"\"); for (; *s; ++s) printf(\"\\\\%03o\", "
            "(unsigned)(unsigned char)*s); printf(\"\\\"\"); }",
            ('extern "C" ' if self.cpp else "") + "int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {",
            "    ut_p = data; ut_left = size;",
            "    ut_fz_registers();",                                                                  # A3-FZ12
            "    ut_before_each();",
            "    ut_fz_calls = 0;",
            "    if (setjmp(ut_fz_jump) != 0) { ut_fz_active = 0; return 0; }",
            "    ut_fz_active = 1;",
            "    ut_sut_reset();" if self.layout.sut_state else "",
            *self.lines,
            "    if (getenv(\"UT_FUZZ_PRINT\")) { printf(\"UT_FUZZ\"); " + " ".join(self.prints) + " printf(\"\\n\"); fflush(stdout); }",
            f"    (void){call};" if fn.return_type.strip() != "void" else f"    {call};",
            "    return 0;", "}", ""])

    def _is_method(self) -> bool:
        owner = self.fn.qualified_name.rsplit("::", 1)[0]
        return any(f.qualified_name.startswith(owner + "::") and f.name.split("::")[-1] == owner.split("::")[-1]
                   for f in self.layout.functions) or bool(re.search(r"\)\s*const\s*$", self.fn.signature))

    def to_input(self, printed: str) -> tuple[list[str], list[str]]:
        """'UT_FUZZ|A0=5|P1=3|...' -> (args, setup statements) as C/C++ source."""
        values = dict(item.split("=", 1) for item in printed.split("|")[1:] if "=" in item)
        setup, args = [], []
        null = "nullptr" if self.cpp else "NULL"
        for key, value in values.items():
            if key.startswith("S:"):
                setup.append(f"{key[2:]} = {value};")
        for i, p in enumerate(self.fn.params):
            t = _plain(p.type)
            if p.kind in ("int", "float"):
                v = values.get(f"A{i}", "0")
                args.append(v if t in ("int", "double") else f"({t})({v})")
            elif p.kind == "bool":
                v = values.get(f"A{i}", "0")
                args.append(("true" if v == "1" else "false") if self.cpp or "bool" in t else v)
            elif p.kind == "enum":
                args.append(p.enum_values[int(values.get(f"E{i}", "0")) % max(len(p.enum_values), 1)])
            elif p.kind == "ptr_scalar":
                base = _plain(p.base)
                if values.get(f"N{i}") == "1":
                    args.append(null)
                else:
                    setup.append(f"{base} ut_v{i} = {values.get(f'P{i}', '0')};")
                    args.append(f"&ut_v{i}")
            elif p.kind in ("struct", "ptr_struct"):
                base = _plain(p.base or p.type)
                setup += self.pointees.get(f"T{i}", [])                                    # A3-FZ2, A2-21ad
                setup.append(f"{base} ut_v{i} = {values.get(f'T{i}', '{0}')};")
                args.append(f"&ut_v{i}" if p.kind == "ptr_struct" else f"ut_v{i}")
            elif p.kind == "cstring":
                args.append(values.get(f"C{i}", '""'))
        return args, setup



