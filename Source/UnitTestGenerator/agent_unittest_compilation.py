    @staticmethod
    def build_systems(repo: Path, component: Path) -> list[str]:
        """Build systems of the component first, then of the repository root [A3-BD2]."""
        found: list[str] = []
        for base in dict.fromkeys([component, repo]):
            names = {p.name for p in base.iterdir()} if base.is_dir() else set()
            for system, markers in (("cmake", {"CMakeLists.txt"}), ("meson", {"meson.build"}),
                                    ("bazel", {"MODULE.bazel", "WORKSPACE", "WORKSPACE.bazel"}),
                                    ("ninja", {"build.ninja"}), ("make", {"Makefile", "makefile", "GNUmakefile"})):
                if names & markers and system not in found:
                    found.append(system)
            if any(n.endswith((".sln", ".vcxproj")) for n in names) and "msbuild" not in found:
                found.append("msbuild")
        return found

    def _configured_command(self, repo: Path) -> str:
        for key, command in self.cfg.build_commands.items():
            if key in (repo.name, str(repo)):
                return command
        return ""

    # ------------------------------------------------------------ compilation databases
    def _entries(self, items: list[dict[str, Any]], repo: Path, original_roots: list[str]) -> tuple[
            list[uc.CompileEntry], dict[str, str]]:
        map_path = uc.path_mapper(repo, original_roots)
        entries, outputs = [], {}
        for item in items:
            directory = str(item.get("directory", "")).replace("\\", "/")
            args = item.get("arguments") or uc.split_command(str(item.get("command", "")))
            if not args:
                continue
            file = str(item.get("file") or self._source_of(args)).replace("\\", "/")
            if not file:
                continue
            path = file if re.match(r"^(/|[A-Za-z]:)", file) else f"{directory}/{file}"
            mapped = map_path(os.path.normpath(path).replace("\\", "/"))
            if not mapped.startswith(uc.REPO_TOKEN + "/"):
                continue                                   # generated or outside the repository
            rel = uc.repo_relative(mapped)
            flags, dropped = uc.translate_flags([str(a) for a in args], directory, map_path)
            language = "cpp" if rel.lower().endswith((".cpp", ".cc", ".cxx", ".c++", ".cp")) or "-x" in args and \
                "c++" in args else "c"
            output = str(item.get("output") or _output_of([str(a) for a in args]))
            entries.append(uc.CompileEntry(file=rel, flags=flags, dropped=dropped, language=language,
                                           output=output.replace("\\", "/")))
            if item.get("output"):
                outputs.setdefault(rel, str(item["output"]))      # the first entry: the tested variant [A3-BD15]
        return entries, outputs

    @staticmethod
    def _source_of(args: list[str]) -> str:
        skip = False
        for a in args[1:]:
            if skip:
                skip = False
                continue
            if a in ("-o", "-MF", "-MT", "-include", "-imacros", "-isystem", "-I", "-D", "-x"):
                skip = True
                continue
            if str(a).lower().endswith(uc.SOURCE_EXT):
                return str(a)
        return ""

    def _client_database(self, db: Path, repo: Path, sut_rel: str) -> tuple[list[uc.CompileEntry], str, str]:
        try:
            items = json.loads(db.read_text(encoding="utf-8", errors="replace"))
        except (OSError, ValueError) as exc:
            raise CaptureFailed(f"cannot read {db}: {exc}") from exc
        root = self._original_root(items, sut_rel)
        entries, _ = self._entries(items, repo, [root] if root else [])
        return entries, f"compilation database {db}", f"{len(entries)} translation units"

    @staticmethod
    def _original_root(items: list[dict[str, Any]], sut_rel: str) -> str:
        """The checkout the database was made in, found from the SUT's own entry."""
        for item in items if isinstance(items, list) else []:
            directory = str(item.get("directory", "")).replace("\\", "/").rstrip("/")
            file = str(item.get("file", "")).replace("\\", "/")
            path = file if re.match(r"^(/|[A-Za-z]:)", file) else f"{directory}/{file}"
            path = os.path.normpath(path).replace("\\", "/")
            if path.lower().endswith("/" + sut_rel.lower()):
                return path[: -len(sut_rel) - 1]
        return ""

    def _repository_database(self, repo: Path, component: Path, sut_rel: str):
        candidates = [component / "compile_commands.json", component / "build" / "compile_commands.json",
                      repo / "compile_commands.json", repo / "build" / "compile_commands.json"]
        candidates += sorted(repo.glob("*/compile_commands.json"))
        for db in dict.fromkeys(candidates):
            if db.is_file():
                return self._client_database(db, repo, sut_rel)
        raise CaptureFailed("no compile_commands.json in the repository")

    # ------------------------------------------------------------ running a build
    def _tool(self, name: str) -> list[str]:
        command = self.tools.command(name)
        if not command:
            raise CaptureFailed(f"{name} is not in the tool manifest: run setup for this repository [TP-12]")
        return command

    def _exec(self, cmd: list[str], cwd: Path, cap: Path, env: dict[str, str] | None = None) -> tuple[int, str]:
        code, out = _run([str(c) for c in cmd], cwd, self.cfg.build_timeout, {**self.chain.env(), **(env or {})})
        with (cap / "build.log").open("a", encoding="utf-8") as fh:
            fh.write(f"$ {' '.join(map(str, cmd))}  (in {cwd})\n{out}\n")
        if code == -9:
            raise CaptureFailed(f"the build exceeded the time limit of {self.cfg.build_timeout:.0f} s [ORC-7]")
        if code in (-126, -127):
            raise CaptureFailed(out.strip()[:300])
        return code, out

    def _build_sut_object(self, ninja: list[str], build: Path, outputs: dict[str, str], cap: Path,
                          layout: uc.LayoutProfile) -> str:
        """Builds only the SUT's object, so its generated headers exist; failures are notes [A3-BD6]."""
        target = outputs.get(layout.sut_file)
        if not target:
            return "configured"
        with contextlib.suppress(ValueError):          # ninja names its targets relative to the build folder [A3-BD15]
            if Path(target).is_absolute():
                target = Path(target).resolve().relative_to(build.resolve()).as_posix()
        code, out = self._exec([*ninja, "-C", str(build), "-k", "0", target], build, cap)
        return "configured; SUT object built" if code == 0 else \
            "configured; building the SUT object failed (generated files may be missing): " + out.strip()[-300:]

    def _cmake(self, repo: Path, component: Path, cap: Path, layout: uc.LayoutProfile):
        cmake, ninja = self._tool("cmake"), self._tool("ninja")
        source = repo if (repo / "CMakeLists.txt").is_file() else component
        build = cap / "cmake"
        # Paths given to CMake with forward slashes: CMake writes some of them into its own scripts, where a
        # backslash is an escape ("Invalid character escape '\U'" for C:\Users\...) [A3-BD15]
        posix = lambda p: Path(p).as_posix()
        cmd = [*cmake, "-S", str(source), "-B", str(build), "-G", "Ninja", "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
               "-DCMAKE_BUILD_TYPE=Debug", f"-DCMAKE_C_COMPILER={posix(self.chain.cc)}",
               f"-DCMAKE_CXX_COMPILER={posix(self.chain.cxx)}", f"-DCMAKE_MAKE_PROGRAM={posix(ninja[0])}"]
        rc = self._resource_compiler()
        if rc:                                   # not the RC variable of the environment [A3-BD15]
            cmd.append(f"-DCMAKE_RC_COMPILER={posix(rc)}")
        code, out = self._exec(cmd, repo, cap)
        db = build / "compile_commands.json"
        if not db.is_file():
            raise CaptureFailed("CMake configure failed: " + _first_error(out, "CMake Error"))
        entries, outputs = self._entries(json.loads(db.read_text(encoding="utf-8")), repo, [])
        return entries, " ".join(cmd), self._build_sut_object(ninja, build, outputs, cap, layout)

    def _resource_compiler(self) -> str:
        """Windows: the toolchain's own resource compiler, next to its C compiler [A3-BD15]."""
        if os.name != "nt":
            return ""
        folder = Path(self.chain.cc).parent
        for name in ("windres.exe", "llvm-windres.exe", "llvm-rc.exe"):      # Windows-GNU expects windres
            if (folder / name).is_file():
                return str(folder / name)
        return ""

    def _meson(self, repo: Path, component: Path, cap: Path, layout: uc.LayoutProfile):
        meson, ninja = self._tool("meson"), self._tool("ninja")
        source = repo if (repo / "meson.build").is_file() else component
        build = cap / "meson"
        env = {"CC": self.chain.cc, "CXX": self.chain.cxx,
               "PATH": os.pathsep.join([str(Path(ninja[0]).parent), self.chain.env().get("PATH", os.environ.get("PATH", ""))])}
        cmd = [*meson, "setup", str(build), str(source), "--buildtype=debug"]
        code, out = self._exec(cmd, repo, cap, env)
        db = build / "compile_commands.json"
        if not db.is_file():
            raise CaptureFailed("meson setup failed: " + out.strip()[-400:])
        entries, outputs = self._entries(json.loads(db.read_text(encoding="utf-8")), repo, [])
        return entries, " ".join(cmd), self._build_sut_object(ninja, build, outputs, cap, layout)

    def _ninja(self, repo: Path, component: Path, cap: Path, layout: uc.LayoutProfile):
        ninja = self._tool("ninja")
        base = component if (component / "build.ninja").is_file() else repo
        code, out = self._exec([*ninja, "-C", str(base), "-t", "compdb"], base, cap)
        try:
            items = json.loads(out[out.index("["):])
        except ValueError as exc:
            raise CaptureFailed("ninja -t compdb gave no database") from exc
        entries, _ = self._entries(items, repo, [])
        return entries, f"ninja -C {base} -t compdb", "compilation database of build.ninja"

    def _make(self, repo: Path, component: Path, cap: Path, layout: uc.LayoutProfile):
        """Make's dry run prints exactly the commands it would run, without running them [A3-BD3]."""
        make = self._tool("make")
        base = component if any((component / n).is_file() for n in ("Makefile", "makefile", "GNUmakefile")) else repo
        cmd = [*make, "-n", "-B", "-k", "-w"]
        code, out = self._exec(cmd, base, cap)
        items, dirs = [], [str(base)]
        for line in out.splitlines():
            m = re.search(r"Entering directory [`'\"](.+?)['\"]", line)
            if m:
                dirs.append(m.group(1))
                continue
            if re.search(r"Leaving directory", line):
                if len(dirs) > 1:
                    dirs.pop()
                continue
            directory = dirs[-1]
            for segment in re.split(r"\s*(?:&&|;)\s*", line.strip()):
                try:
                    tokens = uc.split_command(segment)
                except ValueError:
                    continue
                if not tokens:
                    continue
                if tokens[0] == "cd" and len(tokens) > 1:
                    target = tokens[1]
                    directory = target if re.match(r"^(/|[A-Za-z]:)", target) else f"{directory}/{target}"
                    continue
                if COMPILER_NAME.search(tokens[0].strip("@")) and ("-c" in tokens or "/c" in tokens):
                    source = self._source_of(tokens)
                    if source:
                        items.append({"directory": directory, "arguments": tokens, "file": source})
        if not items:
            raise CaptureFailed("make -n printed no compiler calls" + (": " + out.strip()[-300:] if code else ""))
        entries, _ = self._entries(items, repo, [])
        return entries, " ".join(cmd) + f"  (in {base})", f"dry run: {len(items)} compiler calls"

    def _bazel(self, repo: Path, component: Path, cap: Path, layout: uc.LayoutProfile):
        """Bazel's action graph names every compile action with its arguments [A3-BD3]."""
        bazel = self._tool("bazel")
        cmd = [*bazel, f"--output_base={cap / 'bazel'}", "aquery", "--output=jsonproto",
               'mnemonic("CppCompile", //...)']
        code, out = self._exec(cmd, repo, cap, self.tools.tool_env("bazel"))
        try:
            data = json.loads(out[out.index("{"):])
        except ValueError as exc:
            raise CaptureFailed("bazel aquery failed: " + out.strip()[-400:]) from exc
        items = [{"directory": str(repo), "arguments": a.get("arguments", [])} for a in data.get("actions", [])]
        entries, _ = self._entries(items, repo, [])
        return entries, " ".join(cmd), f"aquery: {len(items)} compile actions"

