def _run(cmd: list[str], cwd: Path, timeout: float, env: dict[str, str] | None = None,
         quiet: bool = False) -> tuple[int, str]:
    """Runs an approved command (never a model-generated string) [A3-128, A3-129]. ``quiet``: no viewer
    event for each run (the many mutant builds of COV-19 are reported once, as one result)."""
    started = time.monotonic()
    try:
        # stdin is never inherited: in an MCP stdio server it is the JSON-RPC channel.
        proc = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout,
                              stdin=subprocess.DEVNULL, env={**os.environ, **(env or {})}, errors="replace")
        if not quiet:
            _program_event(cmd, proc.returncode, time.monotonic() - started)
        return proc.returncode, (proc.stdout or "") + (proc.stderr or "")
    except subprocess.TimeoutExpired as exc:
        out = exc.stdout.decode(errors="replace") if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        return -9, out + "\nUT_TIMEOUT"
    except FileNotFoundError:
        return -127, f"tool not found: {cmd[0]}"
    except OSError as exc:
        return -126, f"{cmd[0]}: {exc}"


def _first_messages(outputs: list[str], limit: int) -> list[str]:
    """The first error lines of compiler or linker output, without the command lines [A3-29d]."""
    lines = []
    for block in outputs:
        for line in block.splitlines():
            line = line.strip()
            if not line or line.startswith("$ ") or line.startswith(">>>"):
                continue
            if re.search(r"error|undefined|multiple definition|duplicate symbol|cannot find|not found|fatal", line, re.I):
                line = re.sub(r"^.*?[/\\]([^/\\]+:\d+(?::\d+)?:)", r"\1", line)          # shorter: file:line:col
                if line not in lines:
                    lines.append(line[:240])
            if len(lines) >= limit:
                return lines
    return lines


def _exit_text(code: int, text: str = "", facts: "uc.PlatformFacts | None" = None) -> str:
    """How a test program ended, for the report [A3-45a, A3-29d]: a signal, an exit code or a time limit - with the
    kind the measured platform facts give it (NC-10, NC-11), or "unknown outcome" when they do not describe it."""
    kind = uc.program_outcome(code, text, facts) if facts is not None else ""
    suffix = "" if not kind or kind in ("normal", "timeout", "watchdog") else \
        " - unknown outcome [NC-12]" if kind == "unknown" else f" - {kind.replace('_', ' ')}"
    return _plain_exit_text(code, text) + suffix


def _plain_exit_text(code: int, text: str = "") -> str:
    if "UT_TIMEOUT" in text and code == -9:
        return "time limit"
    if code < 0:
        try:
            return f"signal {-code} ({signal.Signals(-code).name})"
        except (ValueError, AttributeError):
            return f"signal {-code}"
    if code > 0xFFFF:                                    # Windows NTSTATUS, for example 0xC0000005
        names = {0xC0000005: "access violation", 0xC00000FD: "stack overflow", 0xC0000094: "integer division by zero",
                 0xC0000409: "stack buffer overrun"}
        return f"exit code 0x{code:08X}" + (f" ({names[code]})" if code in names else "")
    return f"exit code {code}"


