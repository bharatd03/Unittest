    def _project_file(self, repo: Path, layout: uc.LayoutProfile):
        """Compile settings of a Visual Studio project (.vcxproj) that lists the SUT [A3-BD5]."""
        sut_name = Path(layout.sut_file).name
        ns = {"m": "http://schemas.microsoft.com/developer/msbuild/2003"}
        for proj in sorted(repo.rglob("*.vcxproj")):
            text = proj.read_text(encoding="utf-8", errors="replace")
            if sut_name not in text:
                continue
            try:
                root = ET.fromstring(text)
            except ET.ParseError:
                continue
            groups = root.findall("m:ItemDefinitionGroup", ns)
            group = next((g for g in groups if "Debug|x64" in (g.get("Condition") or "")), None) or \
                next((g for g in groups if "Debug" in (g.get("Condition") or "")), None) or (groups[0] if groups else None)
            cl = group.find("m:ClCompile", ns) if group is not None else None
            values = lambda tag: [v for v in ((cl.findtext(f"m:{tag}", "", ns) if cl is not None else "") or "").split(";")
                                  if v.strip() and "%(" not in v]
            here = str(proj.parent).replace("\\", "/") + "/"
            expand = lambda v: v.replace("$(ProjectDir)", here).replace("$(MSBuildProjectDirectory)", here.rstrip("/")) \
                .replace("$(MSBuildThisFileDirectory)", here).replace("$(SolutionDir)", str(repo).replace("\\", "/") + "/")
            args = ["cl.exe"] + [f"/D{d}" for d in values("PreprocessorDefinitions")]
            skipped = []
            for inc in values("AdditionalIncludeDirectories"):
                inc = expand(inc)
                (skipped if "$(" in inc else args).append(inc if "$(" in inc else f"/I{inc}")
            args += [f"/FI{expand(f)}" for f in values("ForcedIncludeFiles")]
            std = (cl.findtext("m:LanguageStandard", "", ns) if cl is not None else "") or ""
            std_c = (cl.findtext("m:LanguageStandard_C", "", ns) if cl is not None else "") or ""
            items = []
            for item in root.iter("{%s}ClCompile" % ns["m"]):
                src = item.get("Include")
                if not src:
                    continue
                cpp = src.lower().endswith((".cpp", ".cc", ".cxx"))
                level = (std if cpp else std_c).replace("stdcpp", "c++").replace("stdc", "c").replace("latest", "20")
                items.append({"directory": str(proj.parent), "file": src.replace("\\", "/"),
                              "arguments": args + ([f"/std:{level}"] if level else []) + [src]})
            entries, _ = self._entries(items, repo, [])
            outcome = f"settings of {proj.relative_to(repo)} (Debug)" + \
                (f"; not expanded: {', '.join(skipped)}" if skipped else "")
            return entries, f"read {proj.relative_to(repo)}", outcome
        raise CaptureFailed("no Visual Studio project lists the SUT")

    def _configured(self, command: str, repo: Path, component: Path, cap: Path):
        """A configured build command, run with recording compiler wrappers as CC and CXX [A3-BD3]."""
        shim = cap / "shim"
        shim.mkdir(parents=True, exist_ok=True)
        (shim / "ut_ccrecord.py").write_text(RECORDER, encoding="utf-8")
        wrappers = {}
        for var in ("CC", "CXX"):
            if os.name == "nt":
                path = shim / f"ut_{var.lower()}.cmd"
                path.write_text(f'@"{sys.executable}" "{shim / "ut_ccrecord.py"}" UT_REAL_{var} %*\r\n', encoding="utf-8")
            else:
                path = shim / f"ut_{var.lower()}"
                path.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{shim / "ut_ccrecord.py"}" UT_REAL_{var} "$@"\n',
                                encoding="utf-8")
                path.chmod(0o755)
            wrappers[var] = str(path)
        log = cap / "calls.jsonl"
        env = {"CC": wrappers["CC"], "CXX": wrappers["CXX"], "UT_CC_LOG": str(log),
               "UT_REAL_CC": os.environ.get("CC") or self.chain.cc, "UT_REAL_CXX": os.environ.get("CXX") or self.chain.cxx}
        cmd = uc.split_command(command)
        code, out = self._exec(cmd, component if component.is_dir() else repo, cap, env)
        items = [json.loads(line) for line in log.read_text(encoding="utf-8").splitlines()] if log.is_file() else []
        items = [i for i in items if "-c" in i["arguments"] or "/c" in i["arguments"]]
        if not items:
            for db in [*cap.rglob("compile_commands.json"), repo / "compile_commands.json"]:
                if db.is_file():
                    items = json.loads(db.read_text(encoding="utf-8"))
                    break
        if not items:
            raise CaptureFailed(f"'{command}' compiled nothing through CC/CXX (exit {code})")
        entries, _ = self._entries(items, repo, [])
        return entries, command, f"exit code {code}"


