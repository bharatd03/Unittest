def _planning_counts(lines: list[str]) -> tuple[int, int]:
    """Scenarios accepted from the brain and re-asks, from the planning lines [A1-PL4, KP-8]."""
    accepted = reasks = 0
    for line in lines:
        m = re.search(r"(\d+) scenario\(s\) by .*?, (\d+) call\(s\)", line)
        if m:
            accepted += int(m.group(1))
            reasks += max(0, int(m.group(2)) - 1)
    return accepted, reasks


async def benchmark(config_path: Path, only: list[str] | None = None, knowledge: str = "on") -> int:
    """Seeded-defect benchmark [ORC-16]: every case seeds one known defect into a pilot (or none, as a
    control), runs the whole pipeline and records whether the defect was found and fixed, and
    whether a control received a fix it should not. ``knowledge``: on, off or both - with and
    without the knowledge packs, compared per variant [KP-8]."""
    spec = json.loads((PILOTS / "benchmark.json").read_text(encoding="utf-8"))
    orchestrator = Orchestrator(config_path)
    out = orchestrator.output_root / ("benchmark-" + time.strftime("%Y%m%d-%H%M%S"))
    out.mkdir(parents=True, exist_ok=True)
    variants = ["on", "off"] if knowledge == "both" else [knowledge]
    rows, summaries = [], {}
    previous = os.environ.get("UT_KNOWLEDGE")
    try:
        for variant in variants:
            os.environ["UT_KNOWLEDGE"] = variant          # agents read it when they start [KP-8]
            variant_rows = []
            for case in spec["cases"]:
                if only and case["id"] not in only:
                    continue
                work = out / f"{case['id']}-knowledge-{variant}"
                repo = work / case["pilot"]
                shutil.copytree(PILOTS / case["pilot"], repo)
                sut = repo / case["sut"]
                original = sut.read_text(encoding="utf-8")
                if case.get("find"):
                    if original.count(case["find"]) != 1:
                        variant_rows.append({**case, "knowledge": variant,
                                             "outcome": "invalid case: the seed text must occur exactly once"})
                        continue
                    sut.write_text(original.replace(case["find"], case["replace"]), encoding="utf-8")
                if shutil.which("git"):
                    for args in (("init", "-q"), ("add", "-A"), ("commit", "-q", "-m", "benchmark base")):
                        subprocess.run(["git", "-c", "user.name=ut", "-c", "user.email=ut@localhost", "-C", str(repo),
                                        *args], capture_output=True, stdin=subprocess.DEVNULL)
                print(f"[{case['id']}, knowledge {variant}] {case['description']} ...", flush=True)
                orch = Orchestrator(config_path)
                result = await orch.run(uc.PipelineRequest(repo_root=str(repo), sut_file=case["sut"]))
                norm = lambda t: re.sub(r"\s+", " ", t).strip()
                fixes = result.source_fixes
                restored = any(norm(f.patched_content) == norm(original) for f in fixes)
                if case.get("find"):
                    outcome = ("fixed (original restored)" if restored else "fixed (different correction)" if fixes
                               else "not detected")
                else:
                    outcome = "false fix" if fixes else "no fix (correct)"
                accepted, reasks = _planning_counts(result.planning)
                answered = [p for p in orch.token_log if p.get("outcome") == "answered"]
                variant_rows.append({**case, "knowledge": variant, "outcome": outcome,
                                     "final_state": result.final_state, "tests": result.total_tests,
                                     "iterations": len(result.iterations), "brain_scenarios": accepted,
                                     "reasks": reasks, "brain_calls": len(answered),
                                     "tokens": sum(p.get("used_input_tokens", 0) + p.get("used_output_tokens", 0)
                                                   for p in answered),
                                     "fixes": [f.rationale[:200] for f in fixes], "output": result.output_dir,
                                     "answers": _answer_counts(result.brain_answers),                 # KB-25
                                     "rates": list(result.brain_rates)})                               # ORC-12b
                print(f"[{case['id']}, knowledge {variant}] {outcome}; {result.final_state}", flush=True)
            seeded = [r for r in variant_rows if r.get("find")]
            controls = [r for r in variant_rows if not r.get("find")]
            done = [r for r in variant_rows if "iterations" in r]
            summaries[variant] = {
                "seeded_defects": len(seeded), "detected": sum(r["outcome"].startswith("fixed") for r in seeded),
                "restored_exactly": sum(r["outcome"] == "fixed (original restored)" for r in seeded),
                "controls": len(controls), "false_fixes": sum(r["outcome"] == "false fix" for r in controls),
                "iterations": sum(r["iterations"] for r in done),
                "brain_scenarios_accepted": sum(r["brain_scenarios"] for r in done),
                "reasks": sum(r["reasks"] for r in done), "brain_calls": sum(r["brain_calls"] for r in done),
                "tokens": sum(r["tokens"] for r in done),
                "answers": {step: {k: sum(r.get("answers", {}).get(step, {}).get(k, 0) for r in done)
                                   for k in ("accepted", "fixed", "refused", "examples")}
                            for step in sorted({st for r in done for st in r.get("answers", {})})}}       # KB-25
            rows += variant_rows
    finally:
        if previous is None:
            os.environ.pop("UT_KNOWLEDGE", None)
        else:
            os.environ["UT_KNOWLEDGE"] = previous
    (out / "benchmark.json").write_text(json.dumps({"summary": summaries, "cases": rows}, indent=2), encoding="utf-8")
    md = ["# Seeded-defect benchmark", "",
          "| Knowledge packs | Seeded | Detected and fixed | Restored exactly | Controls | False fixes | Iterations "
          "| Brain scenarios accepted | Re-asks | Brain calls | Tokens |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    md += [f"| {v} | {s['seeded_defects']} | {s['detected']} | {s['restored_exactly']} | {s['controls']} | "
           f"{s['false_fixes']} | {s['iterations']} | {s['brain_scenarios_accepted']} | {s['reasks']} | "
           f"{s['brain_calls']} | {s['tokens']:,} |" for v, s in summaries.items()]
    md += ["", "| Knowledge | Brain step | Accepted | Fixed | Refused | Examples given |",              # KB-25
           "| --- | --- | --- | --- | --- | --- |"]
    md += [f"| {v} | {step} | {c['accepted']} | {c['fixed']} | {c['refused']} | {c['examples']} |"
           for v, s in summaries.items() for step, c in s.get("answers", {}).items()]
    md += ["", "| Case | Knowledge packs | Defect | Outcome | Final state |", "| --- | --- | --- | --- | --- |"]
    md += [f"| {r['id']} | {r['knowledge']} | {r['description']} | {r['outcome']} | {r.get('final_state', '-')} |"
           for r in rows]
    (out / "benchmark.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    print(f"\nResults: {out}")
    return 0 if all(s["false_fixes"] == 0 for s in summaries.values()) else 1


def _answer_counts(lines: list[str]) -> dict[str, dict[str, int]]:
    """KB-25: the report's "step: n accepted, n fixed, n refused; n example(s) given" lines as numbers."""
    out = {}
    for line in lines:
        step, _, rest = line.partition(": ")
        nums = {k: int(m.group(1)) for k in ("accepted", "fixed", "refused")
                for m in [re.search(r"(\d+) " + k, rest)] if m}
        m = re.search(r"(\d+) example", rest)
        out[step] = {**{k: 0 for k in ("accepted", "fixed", "refused")}, **nums, "examples": int(m.group(1)) if m else 0}
    return out


def corpus_cases(only: list[str] | None = None) -> list[tuple[str, Path, dict[str, Any]]]:
    """NC-4: the cases of the construct corpus: (name, folder, case.json)."""
    out = []
    for folder in sorted(CONSTRUCTS.iterdir()) if CONSTRUCTS.is_dir() else []:
        spec = folder / "case.json"
        if spec.is_file() and (not only or folder.name in only):
            out.append((folder.name, folder, json.loads(spec.read_text(encoding="utf-8"))))
    return out


def calibration_config(config_path: Path, brain: str, out: Path) -> Path:
    """BP-8: a copy of the configuration for one brain: only that brain, the profile "full" (every kind is tried),
    a fresh resolution memory (stored recipes would answer without the brain) and no viewer. Relative paths of the
    original are made absolute, so they mean the same files."""
    raw = load_config(config_path)
    base = config_path.resolve().parent
    absolute = lambda v: str(Path(v) if Path(v).is_absolute() else base / v)
    raw.setdefault("brain", {}).setdefault("engine", {})["brain_order"] = [brain]
    profiles = raw.setdefault("profiles", {})
    profiles["brains"] = {**(profiles.get("brains") or {}), brain: "full"}
    comp = raw.setdefault("compilation", {})
    comp["tools_manifest"] = str(uc.manifest_path(config_path))
    comp["work_dir"] = absolute(comp.get("work_dir", "ut_work"))
    kb = raw.setdefault("kb", {})
    kb["db_path"] = str(out / "kb.sqlite3")
    kb["resolutions_path"] = str(out / "resolutions.sqlite3")
    pipe = raw.setdefault("pipeline", {})
    pipe["output_dir"] = str(out / "runs")
    pipe["repo_cache"] = absolute(pipe.get("repo_cache", "ut_cache"))
    raw.setdefault("viewer", {})["enabled"] = False
    raw.setdefault("knowledge", {})["dirs"] = [absolute(d) if not Path(d).is_absolute() and (base / d).is_dir()
                                              else d for d in raw.get("knowledge", {}).get("dirs", ["knowledge"])]
    path = out / "calibration_config.json"
    path.write_text(json.dumps(raw, indent=2), encoding="utf-8")
    return path


def kinds_of_run(result: uc.PipelineResult) -> tuple[set[str], set[str]]:
    """BP-8: the answer kinds a run asked its brain for, and those whose answers passed the checks and the tool."""
    asked, passed = set(), set(result.kinds_used)
    log = Path(result.output_dir) / "brain_answers.jsonl" if result.output_dir else None
    refused: set[str] = set()
    answered: set[str] = set()
    for line in log.read_text(encoding="utf-8").splitlines() if log and log.is_file() else []:
        try:
            rec = json.loads(line)
        except ValueError:
            continue
        kind = uc.STEP_KIND.get(rec.get("step", ""), "")
        if not kind:
            continue
        asked.add(kind)
        (refused if rec.get("kind") == "refused" else answered).add(kind)
        if rec.get("step") == "A1.plan" and "calls_before" in json.dumps(rec.get("answer", "")):
            asked.add("call_sequence")
    passed |= {k for k in answered - refused if k in ("values", "repair", "decision")}
    return asked, passed & asked if asked else passed


async def calibrate(config_path: Path, brain: str, only: list[str] | None = None) -> int:
    """BP-8: runs the construct corpus with one real brain - a command, not a test (TP-21) - and records per answer
    kind the cases whose answers passed the checks and the tool. Writes a profile proposal; the configuration is
    never changed: the user copies the proposal."""
    cases = corpus_cases(only)
    if not cases:
        print(f"No construct corpus at {CONSTRUCTS} [NC-4].")
        return 1
    orchestrator = Orchestrator(config_path)
    out = orchestrator.output_root / "calibration" / f"{brain}-{time.strftime('%Y%m%d-%H%M%S')}"
    out.mkdir(parents=True, exist_ok=True)
    cfg = calibration_config(config_path, brain, out)
    share = orchestrator.book.calibration_share
    asked_n: dict[str, int] = {}
    passed_n: dict[str, int] = {}
    rows = []
    for name, folder, spec in cases:
        work = out / "cases" / name
        shutil.copytree(folder, work)
        print(f"[{name}] {spec.get('construct', '')} ...", flush=True)
        try:
            result = await Orchestrator(cfg).run(uc.PipelineRequest(repo_root=str(work), sut_file=spec["sut"]))
        except ba.AgentFault as exc:
            rows.append({"case": name, "outcome": f"{exc.code}: {exc.message}"[:300]})
            continue
        asked, passed = kinds_of_run(result)
        for k in asked:
            asked_n[k] = asked_n.get(k, 0) + 1
        for k in passed:
            passed_n[k] = passed_n.get(k, 0) + 1
        rows.append({"case": name, "construct": spec.get("construct", ""), "final_state": result.final_state,
                     "asked": sorted(asked), "passed": sorted(passed), "output": result.output_dir})
        print(f"[{name}] {result.final_state}; kinds asked {sorted(asked)}, passed {sorted(passed)}", flush=True)
    per_kind = {k: {"asked": asked_n[k], "passed": passed_n.get(k, 0),
                    "share": round(passed_n.get(k, 0) / asked_n[k], 2)} for k in sorted(asked_n)}
    kinds = [k for k in uc.ANSWER_KINDS if k in per_kind and per_kind[k]["share"] >= share]
    kinds += [k for k in uc.MINIMUM_KINDS if k not in kinds and k not in per_kind]   # not measured: the floor stays
    proposal = {"definitions": {f"calibrated_{brain}": {"kinds": [k for k in uc.ANSWER_KINDS if k in kinds]}},
                "brains": {brain: f"calibrated_{brain}"}}
    data = {"brain": brain, "share_needed": share, "cases": rows, "per_kind": per_kind, "proposal": proposal}
    (out.parent / f"{brain}.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    md = [f"# Calibration of {brain} [BP-8]", "", f"A kind is proposed when at least {share:.0%} of its cases passed "
          "the checks and the tool. Copy the proposal into the \"profiles\" section of ut_config.json to use it; "
          "this command never changes the configuration.", "", "| Kind | Cases asked | Passed | Share | Proposed |",
          "| --- | --- | --- | --- | --- |"]
    md += [f"| {k} | {v['asked']} | {v['passed']} | {v['share']:.0%} | {'yes' if k in kinds else 'no'} |"
           for k, v in per_kind.items()]
    md += ["", "Proposal:", "", "```json", json.dumps(proposal, indent=2), "```", ""]
    (out.parent / f"{brain}.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"Results: {out.parent / (brain + '.json')}")
    return 0


def show_run(folder: Path, port: int = 0, open_browser: bool = True) -> int:
    """VIEW-4: an earlier run again - writes viewer.html (offline) and serves the page until Ctrl+C."""
    events = folder / "events.jsonl"
    if not events.is_file():
        print(f"ut_pipeline: {folder} holds no events.jsonl (no run folder, or the viewer was off).", file=sys.stderr)
        return 2
    replay = ba.write_replay(folder, title="Unit-test generation")
    print(f"Replay file: {replay}")
    server = ba.serve_viewer(ba.ViewHub(folder, app="UT"), port=port, open_browser=open_browser,
                             title="Unit-test generation")
    print(f"Live viewer: {server.url} - Ctrl+C to stop", flush=True)
    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        pass
    finally:
        server.stop()
    return 0


def keep_awake() -> bool:
    """ORC-36: while a run or the benchmark works, the computer does not go to sleep by itself (Windows:
    SetThreadExecutionState; the setting ends with the process). A sleep stops every brain call, compiler and
    test program, and after it the agents' connections time out. Sleep the user chooses still works."""
    if os.name != "nt":
        return False
    try:
        import ctypes
        return bool(ctypes.windll.kernel32.SetThreadExecutionState(0x80000000 | 0x00000001))  # CONTINUOUS|SYSTEM
    except (AttributeError, OSError):
        return False


def run_batch(args: argparse.Namespace) -> int:
    """VIEW-12a: the folders of the command one after another on one viewer page; 0 when every file of every folder
    was verified, else 3."""
    labels = [Path(r.rstrip("/\\")).name if not is_link(r) else r.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")
              for r in args.repo]
    named: dict[str, list[str]] = {}
    for item in args.sut:
        name, _, sut = item.partition("=")
        if not sut:
            raise ba.AgentFault("INVALID_REQUEST", f"--sut {item}: write NAME=FILE [VIEW-12a]")
        named.setdefault(name.strip(), []).append(sut.strip().replace("\\", "/"))
    reqs = [uc.RepositoryRequest(repository=r if is_link(r) else str(Path(r).resolve()), sut_files=named.get(label, []))
            for r, label in zip(args.repo, labels)]
    results = asyncio.run(RepositoryRun(args.config).run_many(reqs, labels))
    lines, code = [f"Every folder, every production file - {time.strftime('%Y-%m-%d %H:%M:%S')}"], 0
    for label, result in zip(labels, results):
        print(f"\n==== {label}")
        summary = Path(result.output_dir) / "summary.md"
        if summary.is_file():
            print(summary.read_text(encoding="utf-8"))
        verified = bool(result.results) and all(r.final_state != "incomplete" for r in result.results)
        lines.append(f"  {label}: every file verified" if verified else
                     f"  {label}: not every file verified (exit code 3) - see its report above")
        lines += [f"    {r.sut_file}: {r.open_summary}" for r in result.results if r.open_summary]    # LA-3a
        code = code if verified else 3
        if any(r.defect_candidates for r in result.results):                                      # A1-37f
            lines.append(f"  {label}: defect candidates (exit code 4): " + "; ".join(
                f"{r.sut_file} {d.candidate_id} line {d.line}" for r in result.results for d in r.defect_candidates))
            code = 4
    if args.summary:
        args.summary.parent.mkdir(parents=True, exist_ok=True)
        args.summary.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return code


