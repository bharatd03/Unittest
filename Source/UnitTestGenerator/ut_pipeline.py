"""Orchestrator - ut_pipeline: runs the unit-test pipeline over MCP.

The orchestrator is deterministic and is the only MCP client of the agents [ORC-1, ORC-2]:

    Agent1 discover -> Agent3 capture -> Agent1 dependencies -> Agent3 probe      [ORC-3]
    Stage A: Agent1 setup plan -> Agent2 / Agent4 fixes -> Agent3 build check   [ORC-4]
    Stage B: Agent1 plan -> KB guidance -> Agent2 generate -> (Agent3 observe -> Agent2
             finalize) -> Agent3 verify -> routing by Agent3 (A3-177)          [ORC-5, ORC-6]
             gaps left without progress -> Agent3 fuzz -> inputs into Agent1's next plan [ORC-5a]

Every handoff is a contract from ut_contracts.py inside BaseAgent's envelope, bound to the SUT
and test-suite signatures [ORC-10] and appended to a hash-chained ledger [ORC-8]. Each run writes
its own output folder [ORC-15].

Input [ORC-17 .. ORC-23]: a git repository link (or a local folder for pilots and development), one
or more SUT files and optionally a branch (default: the server's default branch). The tested commit is
fixed at the start; the repository is cloned once per PC into a cache and every SUT file runs in its
own git worktree of that commit; the build capture is shared per commit.

Delivery [ORC-24 .. ORC-31]: tests only and verified -> one commit to the tested branch (tests, stubs,
harness, ut_reports/<SUT>/); production source changed, or not verified -> a review branch and a pull
request; merging it is the only human approval [ORC-9, ORC-26]. Never a force-push. A local folder
receives the tests directly, and verified fixes on a separate branch [ORC-13a, A4-23c].

The brains suggest, the agents check and decide, the tools act: candidate fixes are reverified one
by one and the smallest passing one is reviewed by a second brain before it is published
[A4-23g, A4-23h]; an estimated build description gets the brain's flag suggestions, kept only when a
compile shows they help [A3-BD11].

Agents are reached as configured in ut_config.json ("pipeline.agents"):
  stdio     - started here as subprocesses, MCP over stdio (default) [ARCH-7]
  http      - FastMCP HTTP servers with bearer tokens, e.g. on a build server [ARCH-8]

Brains [ARCH-1a]: the Claude models the API key in ANTHROPIC_API_KEY can access, in the order of
"brain.engine.brain_order" (default Opus 5.5, Fable 5.1, Sonnet 5.5, Haiku 5.5), else Qwen3 8B on the
remote server (key in QWEN_REMOTE_API_KEY), else Qwen3 8B through Ollama. 'check' shows which are available.
  inprocess - servers created in this process (tests and debugging)

Command line:
  python ut_pipeline.py run --repo <link or folder> --sut <file> [--sut <file> ...] [--branch <name>]
                            [--config ut_config.json]
  python ut_pipeline.py serve [--config ut_config.json]     (MCP tool run_pipeline) [ORC-11]
  python ut_pipeline.py check [--config ut_config.json]     tool manifest, Python packages, brains
  python ut_pipeline.py benchmark [--config ut_config.json] [--knowledge on|off|both]
                                                            seeded-defect benchmark [ORC-16, KP-8]

Tools come only from tools/toolchain.json, written by ut_setup.py [TP-10].
"""
