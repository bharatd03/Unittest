def configured_requirements(raw: dict[str, Any], repository: str) -> list[str]:
    """A1-RQ1: fixed requirement documents per repository in ut_config.json: "requirements": {link or folder:
    [paths]}. A link matches with or without ".git" and a trailing slash, a folder by its full path."""
    def norm(text: str) -> str:
        text = text.strip().rstrip("/\\")
        if is_link(text):
            return re.sub(r"\.git$", "", text).lower()
        return str(Path(text).expanduser().resolve()).lower()
    table = raw.get("requirements") or {}
    wanted = norm(repository)
    return [p for key, paths in table.items() if not key.startswith("_") and isinstance(paths, list)
            and norm(key) == wanted for p in paths if isinstance(p, str)]


def gather_requirements(given: list[str], workspace: Path, target: Path) -> tuple[list[uc.RequirementDocument],
                                                                                  list[str]]:
    """A1-RQ1, A1-RQ2, A1-RQ3, A1-RQ6: each path - a file or a folder; relative: inside the repository (the tested
    commit) when it exists there, else from the folder the command was started in - resolved, its documents of
    an accepted format copied unchanged into ``target``; what cannot be used is returned as a note."""
    caller = Path(os.environ.get("UT_CALLER") or os.getcwd())
    docs: list[uc.RequirementDocument] = []
    notes: list[str] = []
    seen: set[str] = set()
    for entry in dict.fromkeys(p.strip().strip('"') for p in given if p and p.strip()):
        path = Path(entry).expanduser()
        if not path.is_absolute():
            inside = workspace / entry
            path = inside if uc.safe_relpath(entry.replace("\\", "/")) and inside.exists() else caller / entry
        if not path.exists():
            notes.append(f"requirement document {entry} does not exist; the run continues without it [A1-RQ6]")
            continue
        files = sorted(p for p in path.rglob("*") if p.is_file() and not any(part.startswith(".") for part in
                                                                              p.relative_to(path).parts)) \
            if path.is_dir() else [path]
        if len(files) > MAX_REQUIREMENT_FILES:
            notes.append(f"{entry}: only the first {MAX_REQUIREMENT_FILES} of {len(files)} files are read [A1-RQ6]")
            files = files[:MAX_REQUIREMENT_FILES]
        for file in files:
            if file.suffix.lower() not in REQUIREMENT_FORMATS:
                notes.append(f"requirement document {file.name} (given as {entry}) is not read: only ReqIF (.reqif, "
                             ".reqifz), Markdown, plain text or CSV - please give an export in one of them [A1-RQ2]")
                continue
            if file.stat().st_size > MAX_REQUIREMENT_MB * 1024 * 1024:
                notes.append(f"requirement document {file.name} (given as {entry}) is larger than "
                             f"{MAX_REQUIREMENT_MB} MB and is not read [A1-RQ6]")
                continue
            key = str(file.resolve())
            if key in seen:
                continue
            seen.add(key)
            target.mkdir(parents=True, exist_ok=True)
            name = file.name
            k = 1
            while (target / name).exists():
                k += 1
                name = f"{file.stem}-{k}{file.suffix}"
            shutil.copyfile(file, target / name)                    # unchanged, never into the repository [A1-RQ3]
            docs.append(uc.RequirementDocument(name=f"requirements/{name}", path=str((target / name).resolve()),
                                               sha256=uc.file_sha256(target / name),
                                               origin=entry if path.is_file() else f"{entry} ({file.name})"))
    return docs, notes


def is_link(text: str) -> bool:
    """A git repository link (HTTPS, SSH, git://, file://, user@host:path) rather than a local folder."""
    return bool(LINK.match(text.strip()))


def slug(text: str, limit: int = 60) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", text).strip("-.")[:limit] or "x"


class GitError(Exception):
    pass


class Git:
    """git from the tool manifest [TP-10], with the credentials already set up on the PC: Git Credential
    Manager, an SSH key, or a token in the environment variable named in the configuration. A token
    reaches git only through its environment; it is never written to a file, the ledger, a report, a
    commit or a log, and it is removed from every message [ORC-21]."""

    def __init__(self, exe: str, token_env: str = "", token_user: str = "x-access-token", author: str = "",
                 timeout: float = 7200.0):
        self.exe, self.token_env, self.token_user, self.timeout = exe, token_env, token_user, timeout
        m = re.match(r"^\s*(.*?)\s*<(.+?)>\s*$", author or "")
        self.author = (m.group(1), m.group(2)) if m else ("ut-pipeline", "ut-pipeline@localhost")

    def token(self) -> str:
        return os.environ.get(self.token_env, "") if self.token_env else ""

    def env(self, extra: dict[str, str] | None = None) -> dict[str, str]:
        env = {**os.environ, "GIT_TERMINAL_PROMPT": "0", "GCM_INTERACTIVE": "never",
               "GIT_AUTHOR_NAME": self.author[0], "GIT_AUTHOR_EMAIL": self.author[1],
               "GIT_COMMITTER_NAME": self.author[0], "GIT_COMMITTER_EMAIL": self.author[1]}
        token = self.token()
        if token:                                       # https only; SSH keys and GCM need nothing here
            header = "Authorization: Basic " + base64.b64encode(f"{self.token_user}:{token}".encode()).decode()
            env.update({"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "http.extraHeader", "GIT_CONFIG_VALUE_0": header})
        return {**env, **(extra or {})}

    def clean(self, text: str) -> str:
        text = re.sub(r"(\w+://)[^/@\s]+@", r"\1***@", text or "")
        token = self.token()
        return text.replace(token, "***") if token else text

    def _exec(self, args: list[str], stdin: bytes | None, extra: dict[str, str] | None, timeout: float | None):
        try:
            return subprocess.run([self.exe, *args], capture_output=True, input=stdin,
                                  stdin=None if stdin is not None else subprocess.DEVNULL, env=self.env(extra),
                                  timeout=timeout or self.timeout)
        except subprocess.TimeoutExpired as exc:
            raise GitError(f"git {args[0]} exceeded its time limit") from exc
        except OSError as exc:
            raise GitError(f"git could not be started: {exc}") from exc

    def run(self, *args: str, stdin: bytes | None = None, extra: dict[str, str] | None = None,
            timeout: float | None = None, check: bool = True) -> str:
        proc = self._exec(list(args), stdin, extra, timeout)
        if check and proc.returncode != 0:
            message = self.clean(proc.stderr.decode("utf-8", "replace").strip())
            raise GitError(message[-600:] or f"git {args[0]} failed")
        return proc.stdout.decode("utf-8", "replace").strip()

    def run_bytes(self, *args: str) -> bytes | None:
        proc = self._exec(list(args), None, None, 600)
        return proc.stdout if proc.returncode == 0 else None

    def push(self, gitdir: Path, sha: str, branch: str) -> tuple[str, str]:
        """A normal push, never forced [ORC-31]: ok | moved | protected | no_access | error."""
        proc = self._exec(["--git-dir", str(gitdir), "push", "--porcelain", "origin", f"{sha}:refs/heads/{branch}"],
                          None, None, None)
        text = self.clean((proc.stdout + proc.stderr).decode("utf-8", "replace")).strip()
        return ("ok" if proc.returncode == 0 else self.refusal(text)), text

    @staticmethod
    def refusal(text: str) -> str:
        """Why the server refused a push: moved | protected | no_access | error."""
        low = text.lower()
        if "non-fast-forward" in low or "fetch first" in low or "stale info" in low:
            return "moved"
        if any(k in low for k in ("protected branch", "gh006", "hook declined", "not allowed to push",
                                  "pushes to this branch", "protected")):
            return "protected"
        if any(k in low for k in ("permission denied", "permission to", "403", "401", "authentication failed",
                                  "could not read username", "access denied", "not authorized", "write access",
                                  "unable to access", "could not read from remote")):
            return "no_access"
        return "error"


class RepoCache:
    """One bare clone per repository and PC, in the application's cache; later runs only fetch [ORC-20].
    Every run works in its own git worktree of the tested commit, so a large repository is neither
    downloaded nor copied again and no developer's clone is touched."""

    def __init__(self, root: Path, url: str, git: Git):
        self.url, self.git = url, git
        name = slug(re.sub(r"^.*?([^/:]+/[^/:]+?)(?:\.git)?/?$", r"\1", url))
        key = hashlib.sha256(url.encode("utf-8")).hexdigest()[:8]
        self.dir = root / "repos" / f"{name}-{key}.git"
        self.state_file = root / "state" / f"{name}-{key}.json"
        self.empty = root / "empty"

    def gd(self, *args: str) -> list[str]:
        return ["--git-dir", str(self.dir), *args]

    def default_branch(self) -> str:
        """ORC-18: the branch the server reports as its default (normally master or main)."""
        out = self.git.run("ls-remote", "--symref", self.url, "HEAD", timeout=600)
        m = re.search(r"^ref:\s+refs/heads/(\S+)\s+HEAD", out, re.M)
        if not m:
            raise GitError("the server reports no default branch")
        return m.group(1)

    def remote_head(self, branch: str) -> str:
        out = self.git.run("ls-remote", self.url, f"refs/heads/{branch}", timeout=600)
        return out.split()[0] if out.strip() else ""

    def update(self) -> None:
        if not (self.dir / "HEAD").is_file():
            self.dir.parent.mkdir(parents=True, exist_ok=True)
            partial = self.dir.with_name(self.dir.name + ".partial")
            shutil.rmtree(partial, ignore_errors=True)
            self.git.run("clone", "--bare", "--quiet", self.url, str(partial))
            partial.rename(self.dir)
            self.git.run(*self.gd("config", "remote.origin.fetch", "+refs/heads/*:refs/remotes/origin/*"))
        self.git.run(*self.gd("fetch", "--quiet", "--prune", "origin"))

    def branch_head(self, branch: str) -> str:
        return self.git.run(*self.gd("rev-parse", "--verify", "--quiet", f"refs/remotes/origin/{branch}"), check=False)

    def worktree(self, commit: str, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        self.git.run(*self.gd("worktree", "add", "--detach", "--force", str(path), commit))
        return path

    def remove_worktree(self, path: Path) -> None:
        self.git.run(*self.gd("worktree", "remove", "--force", str(path)), check=False)
        self.git.run(*self.gd("worktree", "prune"), check=False)

    def show(self, commit: str, rel: str) -> bytes | None:
        return self.git.run_bytes(*self.gd("show", f"{commit}:{rel}"))

    def files_under(self, commit: str, prefix: str) -> list[str]:
        out = self.git.run(*self.gd("ls-tree", "-r", "--name-only", commit, "--", prefix), check=False)
        return [line for line in out.splitlines() if line]

    def changed(self, a: str, b: str) -> list[str]:
        return self.git.run(*self.gd("diff", "--name-only", a, b), check=False).splitlines()

    def commit(self, parent: str, files: dict[str, bytes | None], message: str) -> str:
        """One new commit on top of ``parent`` with ``files`` (None removes a file): a temporary index,
        nothing checked out, no branch touched."""
        self.empty.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
            env = {"GIT_INDEX_FILE": str(Path(tmp) / "index")}
            index = ["--git-dir", str(self.dir), "--work-tree", str(self.empty)]
            self.git.run(*index, "read-tree", parent, extra=env)
            for rel, data in sorted(files.items()):
                rel = rel.replace("\\", "/")
                if data is None:
                    self.git.run(*index, "update-index", "--force-remove", "--", rel, extra=env)
                    continue
                blob = self.git.run(*self.gd("hash-object", "-w", "--stdin"), stdin=data, extra=env)
                listed = self.git.run(*self.gd("ls-tree", parent, "--", rel), check=False)
                mode = listed.split()[0] if listed else "100644"
                self.git.run(*index, "update-index", "--add", "--cacheinfo", f"{mode},{blob},{rel}", extra=env)
            tree = self.git.run(*self.gd("write-tree"), extra=env)
            return self.git.run(*self.gd("commit-tree", tree, "-p", parent, "-F", "-"), stdin=message.encode("utf-8"))

    def keep_local(self, sha: str, branch: str, out: Path, base: str) -> list[str]:
        """ORC-30 without any write access: a branch in the cache, a patch file and a git bundle."""
        self.git.run(*self.gd("update-ref", f"refs/heads/{branch}", sha))
        out.mkdir(parents=True, exist_ok=True)
        patch = out / "delivery.patch"
        patch.write_bytes(self.git.run_bytes(*self.gd("format-patch", "-1", "--binary", "--stdout", sha)) or b"")
        bundle = out / "delivery.bundle"
        self.git.run(*self.gd("bundle", "create", str(bundle), f"refs/heads/{branch}", f"^{base}"), check=False)
        return [str(patch), str(bundle)]

    def load_state(self) -> dict[str, Any]:
        try:
            return json.loads(self.state_file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}

    def save_state(self, data: dict[str, Any]) -> None:
        self.state_file.parent.mkdir(parents=True, exist_ok=True)
        self.state_file.write_text(json.dumps(data, indent=1), encoding="utf-8")


class PullRequests:
    """Opens pull requests (GitHub, GitHub Enterprise, Bitbucket) or merge requests (GitLab) and reads
    their state [ORC-25, ORC-26]. The token comes from the environment variable named in the configuration
    or from Git Credential Manager (``git credential fill``), and is held in memory only [ORC-21]."""
    DEFAULTS = {"github.com": ("github", "https://api.github.com"), "gitlab.com": ("gitlab", "https://gitlab.com/api/v4"),
                "bitbucket.org": ("bitbucket", "https://api.bitbucket.org/2.0")}

    def __init__(self, url: str, settings: dict[str, dict[str, str]], git: Git):
        self.url, self.git = url, git
        m = re.match(r"^(?:\w+://)?(?:[^@/]+@)?([^/:]+)(?::\d+)?[/:](.+?)(?:\.git)?/?$", url)
        self.host, path = (m.group(1).lower(), m.group(2)) if m else ("", "")
        own = settings.get(url) or settings.get(self.host) or {}
        kind, api = self.DEFAULTS.get(self.host, ("", ""))
        self.kind = own.get("kind", kind)
        self.api = own.get("api", api).rstrip("/")
        self.project = own.get("project", path.lstrip("/"))
        self.token_env = own.get("token_env", "") or git.token_env

    def available(self) -> str:
        if not self.kind or not self.api or not self.project:
            return f"no pull-request service is known for {self.host or 'this link'}; configure pipeline.repositories"
        return ""

    def _token(self) -> str:
        token = os.environ.get(self.token_env, "") if self.token_env else ""
        if token or not self.host:
            return token
        try:                                                       # Git Credential Manager, in memory only
            out = self.git.run("credential", "fill", stdin=f"protocol=https\nhost={self.host}\n\n".encode(),
                               timeout=60)
        except GitError:
            return ""
        return next((line.split("=", 1)[1] for line in out.splitlines() if line.startswith("password=")), "")

    def _call(self, method: str, path: str, body: dict[str, Any] | None = None) -> tuple[int, Any]:
        token = self._token()
        headers = {"Accept": "application/json", "Content-Type": "application/json", "User-Agent": "ut-pipeline"}
        if token:
            headers["Authorization"] = f"Bearer {token}"
        request = urllib.request.Request(self.api + path, data=json.dumps(body).encode() if body is not None else None,
                                         headers=headers, method=method)
        try:
            with urllib.request.urlopen(request, timeout=60) as resp:
                return resp.status, json.loads(resp.read() or b"null")
        except urllib.error.HTTPError as exc:
            try:
                return exc.code, json.loads(exc.read() or b"null")
            except ValueError:
                return exc.code, None
        except (urllib.error.URLError, OSError, ValueError) as exc:
            raise GitError(self.git.clean(f"the pull-request service is not reachable: {exc}")) from exc

    def open(self, head: str, base: str, title: str, body: str) -> tuple[str, str]:
        """(link, number) of a new pull request, or of the one already open for ``head``."""
        quoted = urllib.parse.quote(self.project, safe="")
        if self.kind == "github":
            code, data = self._call("POST", f"/repos/{self.project}/pulls",
                                    {"title": title, "head": head, "base": base, "body": body})
            if code == 422:
                owner = self.project.split("/")[0]
                code, data = self._call("GET", f"/repos/{self.project}/pulls?state=open&head={owner}:{head}")
                data = data[0] if code == 200 and data else None
            if data and data.get("html_url"):
                return data["html_url"], str(data.get("number", ""))
        elif self.kind == "gitlab":
            code, data = self._call("POST", f"/projects/{quoted}/merge_requests",
                                    {"source_branch": head, "target_branch": base, "title": title, "description": body})
            if code == 409:
                code, data = self._call("GET", f"/projects/{quoted}/merge_requests?state=opened&source_branch={head}")
                data = data[0] if code == 200 and data else None
            if data and data.get("web_url"):
                return data["web_url"], str(data.get("iid", ""))
        elif self.kind == "bitbucket":
            code, data = self._call("POST", f"/repositories/{self.project}/pullrequests",
                                    {"title": title, "description": body, "source": {"branch": {"name": head}},
                                     "destination": {"branch": {"name": base}}})
            if data and (data.get("links") or {}).get("html", {}).get("href"):
                return data["links"]["html"]["href"], str(data.get("id", ""))
        else:
            raise GitError(self.available())
        detail = (data or {}).get("message") if isinstance(data, dict) else ""
        raise GitError(f"the pull request was not opened (HTTP {code}{': ' + str(detail)[:200] if detail else ''})")

    def state(self, number: str) -> str:
        quoted = urllib.parse.quote(self.project, safe="")
        if self.kind == "github":
            code, data = self._call("GET", f"/repos/{self.project}/pulls/{number}")
            return ("merged" if data.get("merged_at") else data.get("state", "?")) if code == 200 and data else "?"
        if self.kind == "gitlab":
            code, data = self._call("GET", f"/projects/{quoted}/merge_requests/{number}")
            return data.get("state", "?") if code == 200 and data else "?"
        if self.kind == "bitbucket":
            code, data = self._call("GET", f"/repositories/{self.project}/pullrequests/{number}")
            return str(data.get("state", "?")).lower() if code == 200 and data else "?"
        return "?"


class SutRun:
    """One SUT file of a repository run: its result, its state and where its files are."""
    def __init__(self, sut: str, out: Path, workspace: Path):
        self.sut, self.out, self.workspace = sut, out, workspace
        self.result: uc.PipelineResult | None = None
        self.state: RunState | None = None

    @property
    def verified(self) -> bool:
        return self.result is not None and self.result.final_state == "verified_measured"

    @property
    def changes_source(self) -> bool:
        return bool(self.state and self.state.source_fixes)


class RepositoryRun:
    """ORC-17 .. ORC-31: a repository link (or a local folder), one or more SUT files, a branch. The tested
    commit is fixed at the start; every SUT file runs the whole pipeline in its own worktree; the result
    reaches the repository by one direct commit (tests only, verified) or by a review pull request
    (production-source changes, or not verified). Never a force-push, never another branch changed."""

    def __init__(self, config_path: Path | None = None):
        self.orchestrator = Orchestrator(config_path)
        self.cfg = self.orchestrator.cfg
        self.config_path = self.orchestrator.config_path
        cache = Path(self.cfg.repo_cache)
        self.cache_root = cache if cache.is_absolute() else self.config_path.parent / cache
        self.hub: ba.ViewHub | None = None

    def _git(self) -> Git:
        tools = uc.Tools.load(uc.manifest_path(self.config_path))
        command = tools.command("git")
        if not command:
            raise ba.AgentFault("ENVIRONMENT_ERROR", f"git is not in the tool manifest: {uc.Tools.SETUP_HINT}.")
        return Git(command[0], self.cfg.git_token_env, self.cfg.git_token_user, self.cfg.git_author,
                   self.cfg.git_timeout)

    async def run(self, req: uc.RepositoryRequest) -> uc.RepositoryResult:
        run_id = time.strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:6]
        out = self.orchestrator.output_root / run_id
        out.mkdir(parents=True, exist_ok=True)
        for sut in req.sut_files:
            if not uc.safe_relpath(sut):
                raise ba.AgentFault("INVALID_REQUEST", "SUT files must be relative to the repository and stay inside it.")
        self.hub, server = self._open_viewer(out)                     # one page for all SUT files [VIEW-1]
        try:
            if not is_link(req.repository):
                return await self._folder(req, out)
            return await self._repository(req, out)
        finally:
            await self._close_viewer(server)

    async def run_many(self, reqs: list[uc.RepositoryRequest], labels: list[str]) -> list[uc.RepositoryResult]:
        """VIEW-12a: several repositories or folders one after another, on one viewer page. Each keeps its own
        output folder, reports and summary; the progress counts the files of all of them."""
        run_id = time.strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:6]
        top = self.orchestrator.output_root / run_id
        top.mkdir(parents=True, exist_ok=True)
        for req in reqs:
            for sut in req.sut_files:
                if not uc.safe_relpath(sut):
                    raise ba.AgentFault("INVALID_REQUEST", "SUT files must be relative to the repository.")
        self.hub, server = self._open_viewer(top)
        results: list[uc.RepositoryResult] = []
        try:
            selections: list[uc.FileSelection | None] = []
            ready: list[uc.RepositoryRequest] = []
            for req, label in zip(reqs, labels):                      # every folder's files first [ORC-35]
                selection = None
                if not req.sut_files and not is_link(req.repository):
                    selection = await self.orchestrator.select_files(Path(req.repository).resolve(),
                                                                     top / label / "select", req.compile_commands)
                    req = req.model_copy(update={"sut_files": selection.selected})
                selections.append(selection)
                ready.append(req)
            self.batch = True
            self.progress = Progress(sum(max(1, len(r.sut_files)) for r in ready))
            for index, (req, label, selection) in enumerate(zip(ready, labels, selections)):
                if self.hub is not None:                              # the page stays live until the last folder
                    self.hub.emit("progress", summary=f"{label}: folder {index + 1} of {len(ready)}",
                                  data={"text": f"folder {index + 1} of {len(ready)}: {label}",
                                        "pending": len(ready) - index - 1})        # not the running one
                self.view_prefix = f"{label}: "
                out = top / label
                out.mkdir(parents=True, exist_ok=True)
                if self.hub is not None and self.hub.stop_requested():                        # VIEW-15
                    result = uc.RepositoryResult(repository=req.repository, output_dir=str(out),
                                                 reason=f"not run: {USER_STOP}")
                    self._summary(result, out)
                    results.append(result)
                    continue
                try:
                    result = await (self._folder(req, out) if not is_link(req.repository) else self._repository(req, out))
                except (ba.AgentFault, OSError) as exc:              # this folder only; the others go on
                    message = exc.message if isinstance(exc, ba.AgentFault) else str(exc)
                    result = uc.RepositoryResult(repository=req.repository, output_dir=str(out),
                                                 reason=f"not run: {message}"[:600])
                    self._summary(result, out)
                if selection is not None and result.selection is None:
                    result.selection = selection
                    self._summary(result, out)
                results.append(result)
            if self.hub is not None:
                self.hub.emit("progress", summary="every folder done", data={"text": "100 % - every folder done",
                                                                          "percent": 100, "pending": 0})
        finally:
            self.batch, self.view_prefix = False, ""
            await self._close_viewer(server)
        return results

    def _orchestrator(self) -> Orchestrator:
        orch = Orchestrator(self.config_path)
        orch.hub = self.hub
        orch.progress = getattr(self, "progress", None)                                       # VIEW-11
        orch.view_prefix = getattr(self, "view_prefix", "")                                   # VIEW-12a
        return orch

    def _open_viewer(self, out: Path) -> tuple[ba.ViewHub | None, ba.ViewerServer | None]:
        orch = self.orchestrator
        if not orch.viewer.enabled:
            return None, None
        hub = ba.ViewHub(out, app="UT", metrics=orch.viewer.metrics or DEFAULT_VIEW_METRICS).activate()
        return hub, orch._serve_viewer(hub)

    async def _close_viewer(self, server: ba.ViewerServer | None) -> None:
        hub, self.hub = self.hub, None
        if hub is None:
            return
        if self.orchestrator.viewer.replay:                                                   # VIEW-4
            with contextlib.suppress(OSError):
                ba.write_replay(hub.run_dir, title="Unit-test generation")
        if server is not None:
            await asyncio.sleep(1.0)
            server.stop()
        hub.deactivate()

    async def _repository(self, req: uc.RepositoryRequest, out: Path) -> uc.RepositoryResult:
        result = uc.RepositoryResult(repository=req.repository, output_dir=str(out))
        git: Git | None = None
        try:
            git = self._git()
            cache = RepoCache(self.cache_root, req.repository, git)
            branch = req.branch or await asyncio.to_thread(cache.default_branch)             # ORC-18
            commit = await asyncio.to_thread(cache.remote_head, branch)                      # ORC-19
            if not commit:
                raise GitError(f"the branch {branch} does not exist on the server")
            await asyncio.to_thread(cache.update)                                          # ORC-20
        except (GitError, ba.AgentFault) as exc:                                            # ORC-21
            message = exc.message if isinstance(exc, ba.AgentFault) else str(exc)
            link = git.clean(req.repository) if git else req.repository
            result.repository = link
            result.reason = f"environment_defect: the repository {link} could not be read: {message}"[:600]
            self._summary(result, out)
            return result
        result.branch, result.commit = branch, commit
        if not req.sut_files:                                         # every production file of the commit [ORC-35]
            selecting = out / "worktrees" / "select"
            try:
                await asyncio.to_thread(cache.worktree, commit, selecting)
                result.selection = await self.orchestrator.select_files(selecting, out / "select", req.compile_commands)
            except (GitError, ba.AgentFault, Rejected, OSError) as exc:
                result.reason = f"the production files could not be selected: {exc}"[:600]
                self._summary(result, out)
                return result
            finally:
                with contextlib.suppress(GitError, OSError):
                    await asyncio.to_thread(cache.remove_worktree, selecting)
            req = req.model_copy(update={"sut_files": result.selection.selected})
            if not req.sut_files:
                result.reason = "no production file was found to test [ORC-35]"
                self._summary(result, out)
                return result
        prs = PullRequests(req.repository, self.cfg.repositories, git)
        previous = cache.load_state()
        runs = [SutRun(sut, out / f"{i + 1:02d}-{slug(sut)}", out / "worktrees" / f"{i + 1:02d}")
                for i, sut in enumerate(req.sut_files)]
        if not getattr(self, "batch", False):                     # a batch counts every folder's files [VIEW-12a]
            self.progress = Progress(len(runs))                                               # VIEW-11
        semaphore = asyncio.Semaphore(1 if self.cfg.interactive or self.orchestrator.in_process()       # ORC-23, LA-9
                                      else self.cfg.max_parallel_suts)
        key = hashlib.sha256(f"{req.repository}|{commit}|{req.build_command}|{req.compile_commands}".encode()).hexdigest()[:20]

        async def one(r: SutRun) -> None:
            async with semaphore:
                try:
                    await asyncio.to_thread(cache.worktree, commit, r.workspace)
                    origin = {"repository": git.clean(req.repository), "branch": branch, "commit": commit,
                              "cache_key": key, "previous_review": self._previous(prs, previous.get(r.sut))}
                    pipeline = uc.PipelineRequest(repo_root=str(r.workspace), sut_file=r.sut, test_dir=req.test_dir,
                                                  stub_dir=req.stub_dir, build_command=req.build_command,
                                                  compile_commands=req.compile_commands, requirements=req.requirements)
                    r.result, r.state = await self._orchestrator().run_state(
                        pipeline, workspace=r.workspace, out=r.out, origin=origin)
                    self.progress.done += 1
                except (GitError, ba.AgentFault, OSError) as exc:          # this SUT file only; the others go on
                    message = exc.message if isinstance(exc, ba.AgentFault) else str(exc)
                    r.result = uc.PipelineResult(final_state="incomplete", reason=f"not run: {message}"[:500],
                                                 sut_file=r.sut, repository=git.clean(req.repository),
                                                 branch=branch, commit=commit)
                    r.out.mkdir(parents=True, exist_ok=True)
        await asyncio.gather(*(one(r) for r in runs))
        delivery = Delivery(self, git, cache, prs, req.repository, branch, commit, out)
        result.deliveries = await delivery.deliver(runs)
        state = cache.load_state()
        for record in result.deliveries:
            for sut in record.sut_files:
                if record.kind == "pull_request" and record.url:
                    number = re.search(r"(\d+)/?$", record.url)
                    state[sut] = {"url": record.url, "number": number.group(1) if number else "",
                                  "branch": record.branch, "commit": commit}
        cache.save_state(state)
        for r in runs:
            if r.result is not None:
                record = next((d for d in result.deliveries if r.sut in d.sut_files), None)
                r.result.delivery = self._describe(record)
                (r.out / "result.json").write_text(r.result.model_dump_json(indent=2), encoding="utf-8")
                (r.out / "report.md").write_text(report(r.result), encoding="utf-8")
                result.results.append(r.result)
            if not self.cfg.keep_worktrees:
                await asyncio.to_thread(cache.remove_worktree, r.workspace)
        result.reason = "; ".join(f"{r.sut}: {r.result.final_state if r.result else 'not run'}" for r in runs)
        self._summary(result, out)
        return result

    async def _folder(self, req: uc.RepositoryRequest, out: Path) -> uc.RepositoryResult:
        """A local folder (pilots, development) [ORC-17]: every SUT file works on its own copy of the folder, in
        parallel up to max_parallel_suts (one after another in an interactive run, LA-9); its tests are written into
        the folder when it finishes, under names of its own (A2-21af) [ORC-23]."""
        result = uc.RepositoryResult(repository=str(Path(req.repository).resolve()), output_dir=str(out))
        if not req.sut_files:                                                                 # ORC-35
            result.selection = await self.orchestrator.select_files(Path(req.repository).resolve(), out / "select",
                                                                    req.compile_commands)
            req = req.model_copy(update={"sut_files": result.selection.selected})
            if not req.sut_files:
                result.reason = "no production file was found to test [ORC-35]"
                self._summary(result, out)
                return result
        if not getattr(self, "batch", False):                     # a batch counts every folder's files [VIEW-12a]
            self.progress = Progress(len(req.sut_files))                                      # VIEW-11
        parallel = 1 if self.orchestrator.cfg.interactive or self.orchestrator.in_process() else self.cfg.max_parallel_suts
        semaphore = asyncio.Semaphore(parallel)
        results: dict[str, uc.PipelineResult] = {}

        def request(sut: str, requirements: list[str]) -> uc.PipelineRequest:
            return uc.PipelineRequest(repo_root=str(Path(req.repository).resolve()), sut_file=sut, test_dir=req.test_dir,
                                      stub_dir=req.stub_dir, build_command=req.build_command,
                                      compile_commands=req.compile_commands, requirements=requirements)

        async def one(sut: str) -> None:
            async with semaphore:
                if self.hub is not None and self.hub.stop_requested():                        # VIEW-15
                    self.progress.done += 1
                    results[sut] = uc.PipelineResult(final_state="incomplete", reason=f"not run: {USER_STOP}",
                                                     sut_file=sut)
                    return
                try:
                    r = await self._orchestrator().run(request(sut, list(req.requirements)))
                    again = [d.split(": ", 1)[1].split(" - ", 1)[0] for d in r.decisions
                             if d.startswith("requirement documents given: ")]
                    if again:                                           # LA-9: once more with the documents
                        r = await self._orchestrator().run(request(sut, list(req.requirements) + again))
                    r.delivery = "written to the folder (local folder input)"
                except (ba.AgentFault, OSError) as exc:                  # this SUT file only; the others go on
                    message = exc.message if isinstance(exc, ba.AgentFault) else str(exc)
                    r = uc.PipelineResult(final_state="incomplete", reason=f"not run: {message}"[:500], sut_file=sut)
                self.progress.done += 1
                results[sut] = r

        await asyncio.gather(*(one(sut) for sut in req.sut_files))
        for sut in req.sut_files:                                       # the summary in the order the files were named
            r = results[sut]
            result.results.append(r)
            result.deliveries.append(uc.DeliveryRecord(kind="written_to_folder", sut_files=[sut], reason=r.output_dir))
        result.reason = "; ".join(f"{r.sut_file}: {r.final_state}" for r in result.results)
        self._summary(result, out)
        return result

    @staticmethod
    def _previous(prs: PullRequests, entry: dict[str, str] | None) -> str:
        """ORC-26: the state of the last review pull request for this SUT file."""
        if not entry or not entry.get("url"):
            return ""
        try:
            state = prs.state(entry.get("number", "")) if entry.get("number") else "?"
        except GitError:
            state = "?"
        return f"{entry['url']} ({state})"

    @staticmethod
    def _describe(record: uc.DeliveryRecord | None) -> str:
        if record is None:
            return "not delivered"
        what = {"direct_commit": f"direct commit {record.commit[:12]} to {record.branch}",
                "pull_request": f"pull request {record.url} from {record.branch}",
                "review_branch": f"review branch {record.branch} pushed; pull request not opened",
                "local": "kept locally (no write access): patch file and git bundle in the output folder",
                "written_to_folder": "written to the folder", "none": "not delivered"}[record.kind]
        what = f"{what} - {record.reason}" if record.reason else what
        if record.skipped:                                     # ORC-14: named, never overwritten
            what += "; not overwritten (not generated by this pipeline, or edited since): " + ", ".join(record.skipped)
        return what

    @staticmethod
    def _summary(result: uc.RepositoryResult, out: Path) -> None:
        (out / "summary.json").write_text(result.model_dump_json(indent=2), encoding="utf-8")
        rows = ["# Unit-test run", "", f"- Repository: {result.repository}",
                f"- Branch: `{result.branch or '-'}`, tested commit `{result.commit or '-'}`", ""]
        if result.reason:
            rows += [f"- {result.reason}", ""]
        rows += ["| SUT file | ASIL | Final state | Tests | LC | SC | BC | DC | MC/DC | Delivery |",
                 "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for r in result.results:
            m = r.metrics
            pct = lambda name: uc.metric_text(getattr(m, name)) if m else "-"
            rows.append(f"| {r.sut_file} | {r.asil} | {r.final_state} | {r.passed}/{r.total_tests} | {pct('LC')} | "
                        f"{pct('SC')} | {pct('BC')} | {pct('DC')} | {pct('MCDC')} | {r.delivery.replace('|', '/')} |")
        actions = [(r.sut_file, a) for r in result.results for a in r.action_needed]
        if actions:
            rows += ["", "## Action needed", ""] + [f"- {sut}: {a}" for sut, a in actions]
        if result.selection is not None:                                                      # ORC-35
            rows += ["", f"## Production files selected ({len(result.selection.selected)}) [ORC-35]", ""]
            rows += [f"- {f}" for f in result.selection.selected] or ["- none"]
            rows += ["", f"## Files left out ({len(result.selection.left_out)}) - name a file with --sut to test it",
                     ""] + [f"- {f}" for f in result.selection.left_out]
        (out / "summary.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


class Delivery:
    """ORC-24 .. ORC-31."""

    def __init__(self, owner: RepositoryRun, git: Git, cache: RepoCache, prs: PullRequests, url: str, branch: str,
                 commit: str, out: Path):
        self.owner, self.git, self.cache, self.prs = owner, git, cache, prs
        self.url, self.branch, self.commit, self.out = url, branch, commit, out

    async def deliver(self, runs: list[SutRun]) -> list[uc.DeliveryRecord]:
        done = [r for r in runs if r.result is not None and r.state is not None]
        direct = [r for r in done if r.verified and not r.changes_source]                  # ORC-24
        records = [uc.DeliveryRecord(kind="none", sut_files=[r.sut], reason=r.result.reason)
                   for r in runs if r.result is not None and r.state is None]
        if direct:
            records += await self._direct(direct)
        for r in done:
            if r in direct:
                continue
            why = "production source changed: review needed [ORC-25]" if r.changes_source else \
                f"not verified ({r.result.final_state}): {r.result.reason[:160]} [ORC-28]"
            records.append(await self._review(r, why))
        return records

    # ------------------------------------------------------------ files of one SUT file
    def _files(self, r: SutRun, base: str, delivery: str) -> tuple[dict[str, bytes | None], list[str]]:
        """Tests, stubs, harness and reports (ORC-24, ORC-27); the corrected SUT for a review (ORC-25). A file
        the pipeline did not generate, or that was edited since, is never overwritten (ORC-14)."""
        s, result = r.state, r.result
        files: dict[str, bytes | None] = {}
        skipped: list[str] = []
        bundle = s.best_bundle or (s.bundle if not r.verified else None)
        wanted = {a.path: a.content for a in (bundle.actions if bundle else [])}
        test_dir = (s.layout.writable_test_dir if s.layout else "tests").rstrip("/")
        if bundle:
            for name, content in s.harness.items():
                wanted.setdefault(f"{test_dir}/{name}", content)
        for path, content in wanted.items():
            if not uc.safe_relpath(path):
                skipped.append(path)
                continue
            if not replaceable(self.cache.show(base, path)):
                skipped.append(path)
                continue
            files[path] = stamp(content).encode("utf-8")
        if r.changes_source:                                 # the corrected SUT, only through a review [ORC-25]
            files[r.sut] = (r.workspace / r.sut).read_bytes()
        folder = f"{REPORTS}/{r.sut}"
        for old in self.cache.files_under(base, folder + "/"):                              # ORC-27: replaced
            files[old] = None
        shown = result.model_copy(update={"delivery": delivery, "ledger": f"{folder}/ledger.jsonl",
                                          "output_dir": ""})
        files[f"{folder}/report.md"] = report(shown).encode("utf-8")
        files[f"{folder}/result.json"] = shown.model_dump_json(indent=2).encode("utf-8")
        ledger = r.out / "ledger.jsonl"
        if ledger.is_file():
            files[f"{folder}/ledger.jsonl"] = ledger.read_bytes()
        last = s.last
        coverage = Path(last.run_dir) / "coverage" if last and last.run_dir else None
        for name in ("coverage.lcov", "mcdc.txt"):
            if coverage is not None and (coverage / name).is_file():
                files[f"{folder}/{name}"] = (coverage / name).read_bytes()
        for viewer in (r.out / "viewer.html", self.out / "viewer.html"):                    # VIEW-4
            if viewer.is_file():
                files[f"{folder}/viewer.html"] = viewer.read_bytes()
                break
        for patch in sorted((r.out / "coverage_suggestions").glob("*.patch")):               # COV-13
            files[f"{folder}/coverage_suggestions/{patch.name}"] = patch.read_bytes()
            record = patch.with_suffix(".faults.json")                                       # COV-18
            if record.is_file():
                files[f"{folder}/coverage_suggestions/{record.name}"] = record.read_bytes()
        files[f"{folder}/coverage.json"] = json.dumps(
            {"file": result.metrics.model_dump() if result.metrics else None,
             "functions": [f.model_dump() for f in result.function_coverage]}, indent=1).encode("utf-8")
        return files, skipped

    @staticmethod
    def _coverage_line(result: uc.PipelineResult) -> str:
        if not result.metrics:
            return "not measured"
        return ", ".join(f"{n} {uc.metric_text(getattr(result.metrics, n))}" for n in uc.METRICS)

    # ------------------------------------------------------------ ORC-24, ORC-29, ORC-30
    async def _direct(self, runs: list[SutRun]) -> list[uc.DeliveryRecord]:
        base = self.commit
        head = await asyncio.to_thread(self.cache.remote_head, self.branch)
        if head and head != base:                                                          # ORC-29
            moved = await self._moved(runs, head)
            if moved:
                return [await self._review(r, moved) for r in runs]
            base = head
        files, skipped = {}, []
        for r in runs:
            f, s = self._files(r, base, f"direct commit to {self.branch}")
            files.update(f)
            skipped += s
        message = "\n".join([
            f"Unit tests for {', '.join(r.sut for r in runs)}", "",
            f"Tested commit: {self.commit}" + (f" (verified again on {base})" if base != self.commit else ""),
            *[f"- {r.sut}: {r.result.final_state}; {self._coverage_line(r.result)}" for r in runs], "",
            "Tests only, no production-source change: committed directly [ORC-24].",
            "Generated by the unit-test pipeline (ut_pipeline)."])
        sha = await asyncio.to_thread(self.cache.commit, base, files, message)
        status, text = await asyncio.to_thread(self.git.push, self.cache.dir, sha, self.branch)
        suts = [r.sut for r in runs]
        if status == "ok":
            return [uc.DeliveryRecord(kind="direct_commit", sut_files=suts, branch=self.branch, commit=sha,
                                      reason="tests only, verified [ORC-24]", skipped=skipped)]
        if status == "moved":                               # moved between the check and the push
            await asyncio.to_thread(self.cache.update)
            return [await self._review(r, "the branch moved while the result was being committed [ORC-29]")
                    for r in runs]
        if status == "protected":                                                          # ORC-30
            name = f"ut-review/tests-{self.commit[:10]}"
            return [await self._push_review(runs, files, skipped, base, name, "tests only",
                                            f"the server refused a direct commit to {self.branch} ({text[-160:]}); "
                                            "tests only, no review of production source needed [ORC-30]")]
        if status == "no_access":
            return [self._local(suts, sha, f"ut-local/tests-{self.commit[:10]}", base, skipped, text)]
        return [uc.DeliveryRecord(kind="none", sut_files=suts, reason=f"push failed: {text[-300:]}", skipped=skipped)]

    async def _moved(self, runs: list[SutRun], head: str) -> str:
        """ORC-29: the tests are verified again on the new head; '' when they still build, pass and reach
        the same final state, else the reason for a pull request."""
        await asyncio.to_thread(self.cache.update)
        for r in runs:
            ok, why = await self.owner.orchestrator.reverify(r, head, self.cache, self.out)
            if not ok:
                return f"the branch moved to {head[:12]} during the run and {r.sut}: {why} [ORC-29]"
        return ""

    # ------------------------------------------------------------ ORC-25, ORC-28
    async def _review(self, r: SutRun, why: str) -> uc.DeliveryRecord:
        name = f"ut-review/{slug(r.sut.replace('/', '-'), 80)}-{self.commit[:10]}"
        kind = "production source changed" if r.changes_source else \
            "INCOMPLETE" if not r.verified else "tests only"
        files, skipped = self._files(r, self.commit, f"pull request from {name}")
        return await self._push_review([r], files, skipped, self.commit, name, kind, why)

    async def _push_review(self, runs: list[SutRun], files: dict[str, bytes | None], skipped: list[str], base: str,
                           name: str, kind: str, why: str) -> uc.DeliveryRecord:
        await asyncio.to_thread(self.cache.update)
        parent = self.cache.branch_head(name) or base       # an earlier review branch moves forward [ORC-31]
        if parent != base:                     # what the earlier review commit changed goes back to the base
            for p in self.cache.changed(base, parent):
                if p not in files:
                    files[p] = self.cache.show(base, p)
        suts = [r.sut for r in runs]
        title = f"Unit tests for {', '.join(suts)}: {kind}"
        message = f"{title}\n\nTested commit: {self.commit}\n{why}\n\nGenerated by the unit-test pipeline (ut_pipeline)."
        sha = await asyncio.to_thread(self.cache.commit, parent, files, message)
        status, text = await asyncio.to_thread(self.git.push, self.cache.dir, sha, name)
        if status == "no_access":
            return self._local(suts, sha, name.replace("ut-review/", "ut-local/"), base, skipped, text)
        if status != "ok":
            return uc.DeliveryRecord(kind="none", sut_files=suts, branch=name, reason=f"push failed: {text[-300:]}",
                                     skipped=skipped)
        problem = self.prs.available()
        if problem:
            return uc.DeliveryRecord(kind="review_branch", sut_files=suts, branch=name, commit=sha, skipped=skipped,
                                     reason=f"{why}; {problem}: open a pull request from {name} into {self.branch}")
        try:
            link, number = await asyncio.to_thread(self.prs.open, name, self.branch, title, self._body(runs, kind, why))
        except GitError as exc:
            return uc.DeliveryRecord(kind="review_branch", sut_files=suts, branch=name, commit=sha, skipped=skipped,
                                     reason=f"{why}; {exc}: open a pull request from {name} into {self.branch}")
        return uc.DeliveryRecord(kind="pull_request", sut_files=suts, branch=name, commit=sha, url=link,
                                 skipped=skipped, reason=f"{why}; #{number}")

    def _local(self, suts: list[str], sha: str, name: str, base: str, skipped: list[str], text: str) -> uc.DeliveryRecord:
        kept = self.cache.keep_local(sha, name, self.out, base)
        return uc.DeliveryRecord(kind="local", sut_files=suts, branch=name, commit=sha, skipped=skipped,
                                 reason=f"no write access ({text[-160:]}); {', '.join(kept)} [ORC-30]")

    def _body(self, runs: list[SutRun], kind: str, why: str) -> str:
        """ORC-25: every source change with its location, failure, evidence, results before and after, and
        the unit-test results and coverage."""
        rows = [f"**{kind}** - {why}", "", f"Tested commit: `{self.commit}` on `{self.branch}`", ""]
        for r in runs:
            res, s = r.result, r.state
            rows += [f"## {r.sut}: {res.final_state}", "", f"- Reason: {res.reason}",
                     f"- Tests: {res.total_tests} total, {res.passed} passed, {res.failed} failed",
                     f"- Coverage: {self._coverage_line(res)}", f"- Report: `{REPORTS}/{r.sut}/report.md`", ""]
            for fix in s.source_fixes:
                detail = s.fix_details.get(fix.patch_id, {})
                rows += [f"### Source change {fix.patch_id}: `{fix.file}`, function `{fix.function}`", "",
                         f"- Failure: {detail.get('failure', fix.failure_id)}",
                         f"- Rationale: {fix.rationale}",
                         *[f"- Evidence: {e}" for e in detail.get("evidence", [])],
                         f"- Before the change: {detail.get('before', '-')}",
                         f"- After the change: {detail.get('after', '-')}",
                         f"- Second opinion: {detail.get('review', '-')}", "",
                         "```c", "- " + fix.original_fragment.replace("\n", "\n- "),
                         "+ " + fix.corrected_fragment.replace("\n", "\n+ "), "```", ""]
            if res.target_check:
                rows += [f"Coverage targets, ASIL {res.asil} ({res.asil_source}) [COV-8]:",
                         *[f"- {line}" for line in res.target_check], ""]
            if res.action_needed:
                rows += ["Action needed [COV-11]:", *[f"- {line}" for line in res.action_needed[:15]], ""]
            if res.suggestions:
                rows += ["Source-change suggestions, measured on a trial copy and not applied [COV-13]:",
                         *[f"- {line}" for line in res.suggestions], ""]
            if res.open_items:
                rows += ["Open items:", *[f"- {item}" for item in res.open_items[:15]], ""]
        rows += ["Merging this pull request is the approval: the source files, the unit-test files and the reports "
                 f"reach `{self.branch}` together [ORC-26]."]
        return "\n".join(rows)[:60000]


class PipelineAgent(ba.AgentCore):
    """The orchestrator as an MCP server: tool run_pipeline [ORC-11]."""
    name = "ut_pipeline"

    def __init__(self, settings: ba.Settings | None = None, *, config_path: Path | None = None):
        self.config_path = config_path
        super().__init__(settings)

    def tools(self) -> list[ba.ContractTool]:
        def documents_pre(req, request):
            # A1-RQ1: a client of the MCP tools names requirement documents inside the repository; files elsewhere
            # on this PC are given only on its command line, in its menu or in ut_config.json
            for entry in req.requirements:
                if not uc.safe_relpath(entry.replace("\\", "/")):
                    raise ba.ContractRejected(f"requirement document {entry!r} must be a path inside the repository")

        async def run(req: uc.PipelineRequest, request, scratch):
            return await Orchestrator(self.config_path).run(req)

        async def run_repo(req: uc.RepositoryRequest, request, scratch):
            return await RepositoryRun(self.config_path).run(req)
        return [ba.ContractTool("run_pipeline", uc.PipelineRequest, uc.PipelineResult, run, documents_pre,
                                description="Generate, verify and measure unit tests for one C/C++ file of a folder."),
                ba.ContractTool("run_repository", uc.RepositoryRequest, uc.RepositoryResult, run_repo, documents_pre,
                                description="A git repository link, its SUT files and a branch: tests generated, "
                                            "verified and committed, or a review pull request [ORC-17..ORC-31].")]


