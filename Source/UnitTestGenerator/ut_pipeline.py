    def _idle_reasons(self, result: uc.PipelineResult, s: "RunState") -> dict[str, str]:
        """VIEW-9: why an agent was not called in this run."""
        reached_b = any(i.stage == "verify" for i in result.iterations)
        stopped = f"the run stopped before it was needed: {result.reason}"[:200]
        reasons = {}
        for role, (name, _) in AGENTS.items():
            if name in self._called:
                continue
            if role == "corrector":
                reasons[name] = ("no failing test was classified as a source defect and every target was reached, so no "
                                 "source fix or suggestion was needed (A3-177, COV-12)"
                                 if result.final_state == "verified_measured" else
                                 "no failing test was classified as a source defect (A3-177)" if reached_b else stopped)
            elif role == "kb":
                reasons[name] = "no guidance was asked and nothing verified was there to learn from"
            else:
                reasons[name] = stopped
        return reasons

