    def note_plan(self, plan: uc.UTPlan, iteration: int) -> None:
        """COV-6, COV-10: which strategy each planned item got, its path, its missing vectors and proofs."""
        brains = set()
        why_rules = {}                                                    # function -> why no brain scenario
        for line in plan.planning:
            m = re.match(r"^(.+?): rules - (.+?)(?: \[A1-PL\d+\])?$", line)
            if m:
                reason = m.group(2)
                reason = ("no brain available" if "not available" in reason else
                          "the brain suggested none" if "suggested no scenario" in reason else reason)
                why_rules[m.group(1)] = reason
        for sc in plan.scenarios:
            if sc.made_by.startswith("brain:"):
                who = sc.made_by.split(":", 1)[1]
                brains.add(who.split("/", 1)[0])
                kind = f"scenario by the brain ({who})"
            elif sc.inputs:
                kind = "inputs found by the coverage-guided search"
            else:
                why = why_rules.get(sc.function) or why_rules.get(sc.function.split("::")[-1], "")
                kind = ("rule-based tests (boundary values of the function's literals and macros"
                        + (f"; no brain scenario: {why})" if why else ")"))
            if any(len(v.returns) > 1 for v in sc.stub_values):
                kind += " with a stub return sequence"
            elif sc.stub_values or sc.stub_hints:
                kind += " with stub values"
            for g in sc.gap_ids:
                self.note(g, f"iteration {iteration}: {kind}")
                if sc.required_conditions:
                    self.paths[g] = sc.required_conditions[:8]
        self.brains_last = brains
        for g in plan.gaps:
            if g.required:
                self.missing[g.gap_id] = g.required[:6]
            if g.variant_proofs:                                                # A1-37c, A1-37e: latest
                self.variant_proofs[g.gap_id] = list(g.variant_proofs)
            if ("infeasible_" in g.detail or "unreachable_code" in g.detail) and g.gap_id not in self.proofs:
                self.proofs[g.gap_id] = g.detail
                self.note(g.gap_id, f"iteration {iteration}: deterministic analysis: no test can reach it")
            if g.defect is not None:                                                         # A1-37f
                found = self.defects.setdefault(g.defect.line, g.defect.model_copy(update={
                    "candidate_id": f"D{len(self.defects) + 1}", "items": []}))
                if g.gap_id not in found.items:
                    found.items.append(g.gap_id)
        for found in self.defects.values():                 # the lines its branch makes unreachable are blocked too
            for g in plan.gaps:
                if f"line {found.line}:" in g.detail and "unreachable_code" in g.detail and g.gap_id not in found.items:
                    found.items.append(g.gap_id)
        for line in plan.planning:
            if "[COV-5]" in line or "dropped by the check" in line or "no scenario this time" in line:
                fn = line.split(":", 1)[0]
                if line not in self.rejected.setdefault(fn, []):
                    self.rejected[fn].append(line[:600])              # also facts of the next plan [A1-PL8]

