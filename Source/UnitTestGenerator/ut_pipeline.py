def stamp(content: str) -> str:
    """First line of every delivered file: the hash of the rest. A file whose hash still matches
    was written by this pipeline and not edited since, so it may be replaced [ORC-14a]."""
    body = content.split("\n", 1)[1] if content.startswith(STAMP) else content
    return f"{STAMP}{hashlib.sha256(body.encode('utf-8')).hexdigest()} */\n" + body


def replaceable(data: bytes | None) -> bool:
    """True when the target does not exist or is an unedited file of an earlier run [ORC-14a]."""
    if data is None:
        return True
    text = data.decode("utf-8", errors="replace")
    first, _, rest = text.partition("\n")
    return first.startswith(STAMP) and first[len(STAMP):].split(" ")[0] == hashlib.sha256(rest.encode("utf-8")).hexdigest()


